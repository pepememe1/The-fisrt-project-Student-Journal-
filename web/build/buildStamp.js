/**
 * buildStamp.js — метка сборки: одно и то же число внутри бандла и в `/version.json`.
 *
 * 🔥 ЗАЧЕМ (жалоба Влада 07.09.2026): «после каждого деплоя ломается веб на телефоне,
 * показывается старая версия, а новую видно после перезагрузки страницы».
 *
 * Механизм отказа. Страницы у нас ЛЕНИВЫЕ (`() => import(...)`, см. router/index.js), и
 * имя каждого чанка содержит хеш содержимого. Деплой выкладывает НОВЫЙ каталог статики,
 * а старые файлы уносит. Вкладка, открытая до деплоя, продолжает жить старым кодом — и
 * на первом же переходе просит чанк, которого на сервере больше НЕТ. Браузер отвечает
 * 404, `import()` отклоняется, роутер молча остаётся на месте: человек нажимает пункт
 * меню, и не происходит НИЧЕГО. Ровно это и называют «ломается», а перезагрузка чинит,
 * потому что подтягивает новый index.html с новыми именами.
 *
 * ⚠️ Отказ ТИХИЙ по построению: ошибки в интерфейсе нет, в консоли — одна строка,
 * которую на телефоне никто не видит. Поэтому лечение должно быть автоматическим, а не
 * подсказкой «обновите страницу».
 *
 * Плагин делает ровно одно: кладёт метку в бандл (`__BUILD_STAMP__`) и рядом в
 * `version.json`. Сравнение и перезагрузка — в `src/utils/appVersion.js`.
 *
 * ⚠️ Метка ОДНА на сборку и берётся из одного места. Два независимых значения (одно в
 * бандл, другое в файл) разошлись бы при пересборке и давали вечное «версия сменилась»,
 * то есть бесконечную перезагрузку.
 */
export default function buildStamp(stamp = String(Date.now())) {
  return {
    name: 'gb-build-stamp',
    config() {
      return { define: { __BUILD_STAMP__: JSON.stringify(stamp) } }
    },
    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: 'version.json',
        //Без отступов: файл дёргается опросом, лишние байты тут ни к чему.
        source: JSON.stringify({ stamp }),
      })
    },
  }
}
