/**
 * Категории и подкатегории, которые видит ЭТОТ человек на ЭТОМ устройстве.
 *
 * Два разных отбора, и путать их нельзя:
 *   • `role` — про человека. Шкала оценивания не нужна студенту нигде;
 *   • `device` — про железо. Вибрация не нужна там, где вибрировать нечем, и это
 *     не «скрыть недоступное», а убрать пункт, который открывает пустоту.
 *
 * 🔥 ПОЧЕМУ ОТБОР ЗДЕСЬ, А НЕ `v-if` В РАЗМЕТКЕ РЕЛЬСА. Рельс рисуется в ТРЁХ местах
 * (список категорий на ПК, двухуровневый список на телефоне, выпадающий список
 * подкатегорий) — условие пришлось бы повторить трижды и один раз забыть. Забытое
 * место выглядит исправным: пункт есть, нажимается, и открывает категорию, в которой
 * нет ни одной карточки. Ровно тот же довод, по которому и сам состав вынесен в файл.
 *
 * ⚠️ Категория, у которой после отбора не осталось НИ ОДНОЙ подкатегории, исчезает
 * целиком. Иначе на телефоне без нужной способности остался бы пункт-пустышка.
 *
 * @param {string} role роль вошедшего
 * @param {Object<string, boolean>} caps способности устройства (`{ haptics: true }`).
 *   Отсутствующий ключ считается ОТСУТСТВУЮЩЕЙ способностью: забытая способность
 *   прячет пункт, а не показывает неработающий — ошибаться безопаснее в эту сторону.
 */
export function catsForRole(role, caps = {}) {
  return SETTINGS_CATS
    .filter((c) => !c.role || c.role === role)
    .map((c) => ({
      ...c,
      subs: (c.subs || []).filter(
        (s) => (!s.role || s.role === role)
          //`notRole` — обратный отбор: пункт есть у всех, КРОМЕ названной роли. Нужен
          //там, где возможность общая, а одной роли она противопоказана (второй фактор
          //у администратора: он ей не действует, см. пояснение у пункта).
          && (!s.notRole || s.notRole !== role)
          && (!s.device || caps[s.device] === true),
      ),
    }))
    .filter((c) => c.subs.length > 0)
}

