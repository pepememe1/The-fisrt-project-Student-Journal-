// missedRoute.js — куда девать человека, попавшего не на ту страницу.
//
// Правило (решение Влада, 23.08.2026): промах ВНУТРИ своей роли — обычная опечатка,
// возвращаем на главную; ЧУЖАЯ роль в адресе — «мне сюда нельзя», показываем 404.
// Раньше оба случая молча заканчивались дашбордом, и второй выглядел как сбой.
//
// Вынесено из стража роутера отдельной функцией не ради красоты: правило поведенческое,
// в guard'е его не проверить без браузера, а сломать перестановкой условий — легко.

export const ROLE_PREFIXES = ['student', 'teacher', 'admin', 'parent', 'moderator']

/**
 * @param {string} path — адрес, на который человек метил
 * @param {string} role — его роль
 * @returns {'home'|'notFound'}
 */
export function decideMiss(path, role) {
  const first = String(path || '').split('/')[1] || ''
  // Адрес вообще без роли (/qwerty) — тоже просто промах: показывать «вам сюда нельзя»
  // там, где раздела не существует ни для кого, было бы неправдой.
  if (!ROLE_PREFIXES.includes(first)) return 'home'
  return first === role ? 'home' : 'notFound'
}
