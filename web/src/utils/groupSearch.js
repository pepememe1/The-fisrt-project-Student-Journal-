/**
 * groupSearch.js — поиск учебной группы по названию.
 *
 * 🔥 ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ВНУТРИ СТРАНИЦЫ. Правило тут нетривиальное (регистр,
 * раскладка, разделители, цифры), а внутри `.vue` его не проверить без браузера — тот же
 * приём и та же причина, что у `wheelGeometry.js` и `menuPlacement.js`. Тест зовёт ЭТИ
 * функции, а не повторяет формулу у себя: копия, сверяемая с копией, зеленеет всегда.
 *
 * ⚠️ Нормализация применяется К ОБЕИМ сторонам — и к запросу, и к названию. Односторонняя
 * (только к запросу) разошлась бы на первом же названии с необычным символом: человек
 * видит группу в списке, вводит ровно то, что видит, и не находит её.
 */

// Латиница, СОВПАДАЮЩАЯ НАЧЕРТАНИЕМ с кириллицей (А, В, Е, К, М, Н, О, Р, С, Т, Х, У).
//
// 🔑 Это про человека, который ПЕРЕПИСЫВАЕТ имя латиницей — «K74/1» вместо «К74/1»:
// так группы попадают в переписку, в документы и в адресную строку. Угадывать по
// ЗВУЧАНИЮ нельзя, это путь к ложным совпадениям, — только по виду символа.
//
// ⚠️ ЭТО НЕ РАСКЛАДКА. Здесь стояло «человек не переключил раскладку», и это было
// НЕПРАВДОЙ: на ЙЦУКЕН русская «К» лежит на клавише `r`, а не `k`. То есть набравший
// свою группу по памяти клавиш получал пустой список, а комментарий уверял, что случай
// закрыт. Раскладку закрывает ОТДЕЛЬНАЯ карта ниже; эта — только про начертание.
const LOOKALIKE = {
  a: 'а', b: 'в', c: 'с', e: 'е', h: 'н', k: 'к',
  m: 'м', o: 'о', p: 'р', t: 'т', x: 'х', y: 'у',
}

// Та же клавиша на русской раскладке: QWERTY → ЙЦУКЕН.
//
// 🔥 Ради самого частого промаха: человек знает своё «К74/1» пальцами, забывает
// переключить язык и печатает «r74/1». Почти все группы колледжа на «К», а «К» — это
// клавиша `r`, поэтому без этой карты поиск молчал ровно у большинства.
// ⚠️ Переводим ТОЛЬКО буквы: цифры и разделители на обеих раскладках одинаковы, а
// трогать их значит ломать «74/1» без всякой пользы.
const KEYBOARD = {
  q: 'й', w: 'ц', e: 'у', r: 'к', t: 'е', y: 'н', u: 'г', i: 'ш', o: 'щ', p: 'з',
  a: 'ф', s: 'ы', d: 'в', f: 'а', g: 'п', h: 'р', j: 'о', k: 'л', l: 'д',
  z: 'я', x: 'ч', c: 'с', v: 'м', b: 'и', n: 'т', m: 'ь',
}

/** Запрос, набранный на английской раскладке, — как если бы язык переключили. */
export function toRussianLayout(value) {
  const s = String(value ?? '').toLowerCase()
  let out = ''
  for (const ch of s) out += KEYBOARD[ch] || ch
  return out
}

/** Приведение к сравнимому виду: регистр, раскладка, лишние пробелы. */
export function normalizeGroup(value) {
  const s = String(value ?? '').toLowerCase().replace(/\s+/g, ' ').trim()
  let out = ''
  for (const ch of s) out += LOOKALIKE[ch] || ch
  return out
}

/**
 * «Сжатая» форма — только буквы и цифры.
 *
 * ⚠️ Ради неё всё и затевалось: портал пишет группы как «К74/1», «316-1 ЭиЭ», «К14,15.0»,
 * и разделитель человек помнит последним. Запрос «741» обязан находить «К74/1», хотя
 * подстрокой он в него не входит. Здесь же сам собой закрывается поиск ПО ЦИФРАМ.
 */
export function compactGroup(value) {
  return normalizeGroup(value).replace(/[^0-9a-zа-яё]/g, '')
}

/** Только цифры названия — запасной ход, когда буквы человек пишет иначе. */
export function digitsOf(value) {
  return String(value ?? '').replace(/\D/g, '')
}

/**
 * Прочтения запроса: как написано и как если бы забыли переключить раскладку.
 *
 * ⚠️ Два прочтения, а не одно «умное»: карты конфликтуют на одной букве — `k` по
 * НАЧЕРТАНИЮ это «к», а по КЛАВИШЕ «л». Выбрать за человека нельзя, поэтому пробуем оба
 * и берём лучшее совпадение. Одинаковые прочтения (запрос уже кириллицей) не дублируем.
 */
function queryReadings(value) {
  const asWritten = normalizeGroup(value)
  const asTyped = normalizeGroup(toRussianLayout(value))
  return asTyped === asWritten ? [asWritten] : [asWritten, asTyped]
}

/** Ранг одного прочтения против уже разобранного названия; -1 — не отвечает. */
function rankOne(n, cn, q) {
  if (n === q) return 0
  if (n.startsWith(q)) return 1
  if (n.includes(q)) return 2
  const cq = compactGroup(q)
  if (!cq) return -1
  if (cn === cq) return 3
  if (cn.startsWith(cq)) return 4
  if (cn.includes(cq)) return 5
  return -1
}

/**
 * Насколько хорошо название отвечает запросу: 0 — лучше всего, -1 — не отвечает вовсе.
 *
 * ⚠️ Ранг, а не «да/нет». Иначе «К7» показывает К7, К70, К71 … К79 вперемешку, и точное
 * совпадение тонет в середине списка — ровно то, ради чего поиск и открывали.
 */
export function groupMatchRank(name, query) {
  if (!normalizeGroup(query)) return 0   //пустой запрос — подходят все
  const n = normalizeGroup(name)
  const cn = compactGroup(name)
  let best = -1
  for (const q of queryReadings(query)) {
    const r = rankOne(n, cn, q)
    if (r >= 0 && (best < 0 || r < best)) best = r
  }
  if (best >= 0) return best
  // 🔑 ЗАПАСНОЙ ХОД ПО ЦИФРАМ — ТОЛЬКО ДЛЯ ЗАПРОСА БЕЗ БУКВ.
  // Пока он работал на любом запросе, «к9» возвращало К19, К29, К39: буквенная часть
  // отбрасывалась целиком, и человек получал не свою группу, а всё с девяткой внутри.
  // Набрал букву — значит имел её в виду; лучше не найти, чем найти не то.
  const dq = digitsOf(query)
  if (dq && !/[a-zа-яё]/.test(normalizeGroup(query)) && digitsOf(name).includes(dq)) return 6
  return -1
}

/**
 * Отбор и сортировка списка групп под запрос.
 *
 * ⚠️ Сортировка СТАБИЛЬНАЯ: при равном ранге сохраняем исходный порядок портала. Свой
 * алфавитный порядок поверх чужого выглядел бы как перетасовка — человек ищет группу
 * там, где видел её в прошлый раз.
 */
export function filterGroups(names, query) {
  const src = Array.isArray(names) ? names : []
  return src
    .map((name, i) => ({ name, i, rank: groupMatchRank(name, query) }))
    .filter((x) => x.rank >= 0)
    .sort((a, b) => (a.rank - b.rank) || (a.i - b.i))
    .map((x) => x.name)
}
