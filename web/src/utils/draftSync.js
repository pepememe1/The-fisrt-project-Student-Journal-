/**
 * Догонять ли сохранённое значение.
 *
 * @param {*} draft — что сейчас в поле
 * @param {*} lastSynced — сохранённое значение, которое поле показывало в прошлый раз
 * @returns {boolean} true — человек поле НЕ трогал, черновик можно обновить
 *
 * ⚠️ Сравниваем с ПРОШЛЫМ сохранённым, а не с новым. Сравнение с новым — это и есть
 * пойманный дефект: оно объявляет правкой любое изменение, пришедшее с сервера.
 */
export function shouldFollow(draft, lastSynced) {
  return draft === lastSynced
}

/**
 * Один шаг синхронизации: вернуть новое состояние пары (черновик, метка).
 *
 * @param {{draft:*, lastSynced:*}} state
 * @param {*} incoming — значение, пришедшее с сервера
 * @returns {{draft:*, lastSynced:*}}
 *
 * ⚠️ Метка `lastSynced` двигается ВСЕГДА, даже когда черновик остался нетронутой правкой
 * человека. Иначе следующее обновление с сервера сравнивалось бы с устаревшей меткой и
 * черновик перестал бы догонять сохранённое НАВСЕГДА — та же вечная «правка», только
 * пришедшая с другой стороны.
 */
export function syncDraft(state, incoming) {
  const follow = shouldFollow(state.draft, state.lastSynced)
  return { draft: follow ? incoming : state.draft, lastSynced: incoming }
}

/**
 * Сброс черновика к сохранённому («Отменить»).
 *
 * ⚠️ Метку двигаем ТОЖЕ. Без этого после отмены черновик равен сохранённому, а метка
 * отстала — и первое же обновление с сервера снова разошлось бы с черновиком, зажигая
 * «есть несохранённые изменения» на ровном месте.
 */
export function resetDraft(saved) {
  return { draft: saved, lastSynced: saved }
}
