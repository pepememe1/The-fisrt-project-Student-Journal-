/** Свежесть расписания: меняется реже раза в сутки, шести часов с запасом хватает. */
export const STALE_MS = 6 * 60 * 60 * 1000
/** Пауза после осечки. Пять минут — «вышел из здания, поймал сеть», а не полдня. */
export const RETRY_MS = 5 * 60 * 1000

/**
 * Стоит ли идти в сеть прямо сейчас.
 *
 * @param {number} now   текущее время
 * @param {number} okAt  когда расписание в последний раз обновилось УСПЕШНО (0 — никогда)
 * @param {number} tryAt когда в последний раз ПЫТАЛИСЬ (0 — никогда)
 */
export function shouldRefresh({ now, okAt = 0, tryAt = 0 } = {}) {
  //Свежие данные есть — не трогаем. Это и есть основной ограничитель.
  if (now - okAt < STALE_MS) return false
  //Данные несвежие, но мы только что пробовали и не смогли — не долбим сеть.
  if (now - tryAt < RETRY_MS) return false
  return true
}
