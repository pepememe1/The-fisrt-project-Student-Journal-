// ━━ ЗАЧЕМ ОТДЕЛЬНО ОТ КОМПОНЕНТА ━━
// Две просьбы Влада (05.09.2026) сходятся именно здесь:
//  • «меню над сообщением урезать максимально» — на снимке нашего мессенджера восемь
//    пунктов плюс две строки реакций, и меню не помещается в окно;
//  • «при выделении текста и нажатии ПКМ выйдет меню как в телеграм, в зависимости от
//    того, где мы выделяем (ЛС или канал)».
// «В зависимости от» — это правило, а не вёрстка, и проверять его надо числами
// (`web/tests/messageMenu.test.mjs`), а не глазами по скриншоту.
//
// ━━ ЧТО ИМЕННО УРЕЗАНО И ПОЧЕМУ ИМЕННО ТАК ━━
// Осталось ШЕСТЬ строк первого уровня — ровно столько же, сколько в присланных снимках
// Telegram. Остальное уехало под «Ещё», а не удалено: «Зачитать сообщение», «Напомнить»
// и «Реакции» — рабочие функции, за которыми приходят редко, и вырезать их значило бы
// чинить длину меню потерей возможностей.
//
// ⚠️ «Перевести» уехало туда же. В нижней панели композера была ВТОРАЯ кнопка перевода,
// открывавшая тот же диалог, что и кнопка в шапке беседы, — её убрали совсем (просьба
// «кнопку перевода убери из меню снизу, т.к. она уже есть сверху»). А перевод ОДНОГО
// сообщения — другое действие, и оно осталось, просто не на первом уровне.
//
// ⚠️ У УДАЛЁННОГО сообщения меню состоит из одного «Выделить»: остальное относится к
// тексту, которого больше нет. Показывать «Ответить» на тумбстоуне — предлагать
// невыполнимое.

/**
 * Обычное меню сообщения (без выделения текста).
 *
 * @param {object} m — сообщение как его отдаёт сервер (mine/deleted/pinned/body/kind)
 * @returns {{primary: string[], more: string[]}} ключи действий
 */
export function messageMenuItems(m) {
  const msg = m || {}
  if (msg.deleted) return { primary: ['select'], more: [] }

  const primary = ['reply', 'copy', 'forward']
  primary.push(msg.pinned ? 'unpin' : 'pin')
  primary.push('delete')
  // «Пожаловаться» — только на ЧУЖОЕ: жалоба на себя не имеет адресата, а место в
  // коротком меню стоит дорого. У своего сообщения это место занимает «Выделить».
  primary.push(msg.mine ? 'select' : 'report')

  const more = []
  if (msg.body) more.push('speak')
  if (!msg.mine && msg.body) more.push('translate')
  more.push('remind')
  if (msg.mine) more.push('reactions-info')
  else more.push('select')
  return { primary, more }
}

/**
 * Меню ПО ВЫДЕЛЕННОМУ ТЕКСТУ — как в Telegram (снимки 02 и 03 задания).
 *
 * Разница между чужим и своим сообщением взята оттуда же дословно: у чужого есть
 * «Пожаловаться», у своего вместо неё «Закрепить» и «Удалить».
 *
 * @param {object} m — сообщение
 * @param {object} ctx
 * @param {string} ctx.kind — вид беседы: 'direct' | 'group' | 'channel'
 * @param {boolean} ctx.canPin — есть ли право закреплять в этой беседе
 * @param {boolean} ctx.canLink — умеет ли клиент дать ссылку на сообщение
 *
 * ⚠️ «Копировать ссылку на сообщение» показываем ТОЛЬКО когда ссылка действительно есть
 * (`canLink`). Пункт, кладущий в буфер обмена адрес, по которому ничего не открывается,
 * хуже отсутствующего: человек отправит его собеседнику и узнает об этом от него.
 *
 * ⚠️ В ЛИЧНОЙ переписке ссылки нет намеренно: беседа видна только двоим, и «ссылка на
 * сообщение» из неё либо не откроется у третьего, либо откроет ему чужую переписку.
 * Поэтому вид беседы здесь решает не оформление, а состав.
 */
export function selectionMenuItems(m, ctx = {}) {
  const msg = m || {}
  const kind = ctx.kind || 'direct'
  if (msg.deleted) return []

  const items = ['quote-reply', 'copy-selection']
  if (ctx.canLink && kind !== 'direct') items.push('copy-link')
  items.push('forward')
  if (msg.mine) {
    if (ctx.canPin) items.push(msg.pinned ? 'unpin' : 'pin')
    items.push('delete')
  } else {
    items.push('report')
  }
  items.push('select')
  return items
}
