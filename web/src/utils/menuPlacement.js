// menuPlacement.js — куда класть всплывающее меню, чтобы оно ЦЕЛИКОМ было на экране.
//
// ━━ ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ ━━
// Живая жалоба Влада (05.09.2026): «если нажимаем ПКМ по сообщению — вылазит меню, но
// она уезжает за край окна если сообщение внизу». На снимке видно ровно это: меню
// нарисовано ВНИЗ от точки нажатия и обрезано нижней границей, последний пункт у самого
// края, дальше ничего не помещается.
//
// 🔥 ПРИЧИНА БЫЛА В ЧИСЛЕ, ВПИСАННОМ РУКАМИ. Прежний кламп выглядел так:
//     top: Math.min(y, window.innerHeight - 360)
// то есть высота меню объявлялась КОНСТАНТОЙ 360. Меню же собирается из пунктов по
// правам (своё/чужое, закреплено, удалено, есть ли текст) плюс две строки реакций — его
// настоящая высота гуляет вдвое. Снимок значения снова разошёлся с тем, что он описывает,
// — наш обычный класс: константа не краснеет и не жалуется, она просто перестаёт быть
// правдой, а видно это только глазами и только в крайнем положении.
//
// ⚠️ Поэтому здесь НЕТ размеров меню — их приносит вызывающий, ИЗМЕРИВ элемент
// (`getBoundingClientRect` после отрисовки). Функция отвечает только на вопрос «куда»,
// зато отвечает проверяемо: `web/tests/menuPlacement.test.mjs` гоняет её числами, без
// браузера.
//
// ⚠️ Тот же дефект уже ловили на мобильном меню смены аватарки — поэтому модуль общий, а
// не «функция внутри одного .vue». Второй экземпляр этой логики разошёлся бы с первым.

/** Отступ от края окна: меню, прижатое вплотную, читается как обрезанное. */
export const EDGE = 8

/**
 * Положение всплывающего окна рядом с точкой (x, y).
 *
 * @param {object} p
 * @param {number} p.x, p.y — точка нажатия (координаты окна, как у события мыши)
 * @param {number} p.w, p.h — ИЗМЕРЕННЫЕ размеры меню
 * @param {number} p.vw, p.vh — размеры окна
 * @param {number} [p.gap] — просвет между точкой и меню при развороте вверх
 * @returns {{left:number, top:number, placement:'down'|'up'}}
 *
 * Правила, и каждое куплено отдельным случаем:
 *  1. по умолчанию — ВНИЗ от точки: так меню не закрывает то, по чему нажали;
 *  2. не помещается вниз, а вверх помещается → разворачиваем ВВЕРХ. Это и есть починка
 *     жалобы: у сообщения на дне ленты места вниз нет никогда;
 *  3. не помещается НИКУДА (меню выше окна — телефон в альбомной ориентации) → прижимаем
 *     к верхнему краю. Обрезать снизу нельзя: там лежат «Удалить» и «Пожаловаться», то
 *     есть именно те пункты, ради которых меню и открывают;
 *  4. по горизонтали — тот же кламп, и он был единственным, что работало и раньше.
 */
export function placeMenu({ x, y, w, h, vw, vh, gap = 6 }) {
  const left = Math.max(EDGE, Math.min(x, vw - w - EDGE))

  const fitsDown = y + h + EDGE <= vh
  const fitsUp = y - h - gap - EDGE >= 0
  if (fitsDown) return { left, top: y, placement: 'down' }
  if (fitsUp) return { left, top: y - h - gap, placement: 'up' }
  // Не помещается ни так, ни так: показываем СВЕРХУ вниз от края и полагаемся на
  // собственную прокрутку меню (`max-height` у контейнера). Молча обрезать нижние
  // пункты — то же самое, что их не иметь.
  return { left, top: EDGE, placement: 'down' }
}

/**
 * Максимальная высота меню в этом окне — чтобы оно прокручивалось, а не обрезалось.
 * Отдельно от `placeMenu`, потому что нужна ДО измерения: её ставят стилем, и уже
 * ограниченное меню меряют.
 */
export function menuMaxHeight(vh) {
  return Math.max(120, vh - EDGE * 2)
}

/**
 * Положение меню, привязанного К КНОПКЕ (а не к точке нажатия): меню доступности,
 * выпадающие списки в шапке. Отличие от `placeMenu` в том, что здесь есть ЯКОРЬ с
 * высотой — уходя вверх, меню обязано кончаться над кнопкой, а не над её серединой.
 *
 * @param {object} p
 * @param {{top:number,bottom:number,left:number,right:number}} p.anchor — прямоугольник кнопки
 * @param {number} p.w, p.h — ИЗМЕРЕННЫЕ размеры меню
 * @param {number} p.vw, p.vh — размеры окна
 * @param {'up'|'down'} [p.prefer] — куда открывать, если помещается и туда, и туда
 * @param {'left'|'right'} [p.align] — какой край меню равнять по кнопке
 *
 * ⚠️ Заведено вторым вызывающим, а не «на будущее»: в `AccessibilityMenu` стоял
 * комментарий «вылезло за край — прижимаем», а прижималась только ГОРИЗОНТАЛЬ. Меню
 * доступности, открытое вверх у верхней кромки экрана, уезжало за неё целиком — и
 * заметить это можно было только на низком окне. Комментарий, обещающий проверку,
 * которой нет, — тот же класс дефекта, что константа 360 в меню сообщения.
 */
export function placeAnchored({ anchor, w, h, vw, vh, prefer = 'down', align = 'right', gap = 8 }) {
  const left = align === 'right'
    ? Math.max(EDGE, Math.min(anchor.right - w, vw - w - EDGE))
    : Math.max(EDGE, Math.min(anchor.left, vw - w - EDGE))

  const upTop = anchor.top - gap - h
  const downTop = anchor.bottom + gap
  const fitsUp = upTop >= EDGE
  const fitsDown = downTop + h + EDGE <= vh

  if (prefer === 'up' && fitsUp) return { left, top: upTop, placement: 'up' }
  if (prefer === 'down' && fitsDown) return { left, top: downTop, placement: 'down' }
  if (fitsDown) return { left, top: downTop, placement: 'down' }
  if (fitsUp) return { left, top: upTop, placement: 'up' }
  //Не помещается никуда — прижимаем к верху и полагаемся на прокрутку самого меню.
  return { left, top: EDGE, placement: 'down' }
}
