/**
 * Текст вопроса при уходе. Незнакомая пасхалка получает нейтральный, но честный.
 *
 * @param {string} egg — что на экране.
 * @param {boolean} again — ачивка за неё УЖЕ получена: тогда реплика другая, см. выше.
 */
export function leaveAsk(egg, again = false) {
  if (again) {
    return LEAVE_ASK_AGAIN[egg] || {
      title: 'Эта находка уже ваша',
      message: 'Достижение за неё вы получили раньше. Пасхалка на экране — уйти?',
      ok: 'Уйти', cancel: 'Остаться',
    }
  }
  return LEAVE_ASK[egg] || {
    title: 'Сейчас на экране пасхалка',
    message: 'Если уйти со страницы, она пропадёт, а достижение останется закрытым. Всё равно уйти?',
    ok: 'Уйти', cancel: 'Остаться',
  }
}

export const useEasterStore = defineStore('easterEggs', () => {
  // Какие ачивки у человека УЖЕ есть. Нужны ровно для одного: не спрашивать «остаться?»
  // про находку, которая ему больше ничего не даст.
  //
  // ⚠️ Список именно СВОИХ ачивок, и его отдаёт сервер. Здесь он держится копией только
  // чтобы не ходить на сервер при каждом переходе между вкладками; решение «выдать или
  // нет» по-прежнему серверное (`claim` сверяет след срабатывания).
  const owned = ref(new Set())
  const active = ref('')          // полноэкранная сцена, которая играет прямо сейчас
  const inPage = ref({})          // { id: true } — пасхалки внутри страницы, их может быть несколько
  const lastUnlocked = ref(null)  // для тоста «достижение открыто»
  // 🔥 ЗДЕСЬ БЫЛ ОБЩИЙ ФЛАГ `busy`, И ОН ГЛУШИЛ ПОЧТИ ВСЕ ПАСХАЛКИ СТРАНИЦ.
  //
  // Порядок событий при переходе на вкладку такой: сначала срабатывает сторож маршрута
  // в оболочке и просит дерево Делтарун, а через несколько МИЛЛИСЕКУНД монтируется сама
  // страница и просит свою пасхалку — Hotline в мессенджере, штамп в профиле, G-Man в
  // настройках. Запрос дерева к этому моменту ещё летит, флаг поднят, и просьба
  // страницы молча отбрасывалась. То есть Hotline, Papers Please, Undertale и G-Man
  // почти НИКОГДА не бросались вовсе — Влад справедливо сообщил, что «кучу раз
  // перезаходил и ничего».
  //
  // ⚠️ Флаг был нужен против ДВОЙНОГО броска ОДНОЙ И ТОЙ ЖЕ пасхалки (двойное
  // монтирование, быстрый повторный переход). Эту задачу он решал, а заодно решал и ту,
  // которую решать не должен был. Поэтому теперь он ПОШТУЧНЫЙ: одна пасхалка не мешает
  // другой, но сама себя по-прежнему не задваивает.
  const inFlight = new Set()

  /** Бросок. Принимает id или список (тогда сработает не больше ОДНОЙ). */
  async function roll(egg) {
    const auth = useAuthStore()
    // Пасхалки только у студентов. Сервер это тоже проверяет — здесь просто не тратим
    // запрос: преподаватель и админ переключают вкладки не реже, а показывать нечего.
    if (auth.role !== 'student' || active.value) return null
    const key = Array.isArray(egg) ? egg.join('|') : egg
    if (inFlight.has(key)) return null
    inFlight.add(key)
    try {
      const body = Array.isArray(egg) ? { eggs: egg } : { egg }
      const { data } = await easterApi.roll(body)
      if (data.egg) place(data.egg)
      return data.egg || null
    } catch {
      return null            // нет сети или сервер занят — пасхалка просто не выпала
    } finally {
      inFlight.delete(key)
    }
  }

  /**
   * Снять метки аватарки (DOOM и Detroit) перед новым входом.
   *
   * 🔥 Без этого свечение с прошлого входа не пропадало: `reset()` при выходе чистит
   * стор, но если человек вошёл заново в той же вкладке И сервер выбрал ДРУГУЮ метку,
   * старая оставалась рядом с новой — на аватарке оказывались и кольцо, и свечение
   * разом. Влад поймал это как «вышел, зашёл, а аура не пропадает».
   */
  function easter_clearAvatar() {
    const next = { ...inPage.value }
    delete next.doom_avatar
    delete next.detroit_led
    inPage.value = next
  }

  /** Забрать список своих ачивок. Тихо: без него всё работает, просто вопрос лишний. */
  async function loadOwned() {
    try {
      const { data } = await meApi.achievements()
      owned.value = new Set((data.unlocked || []).map((r) => r.id))
    } catch { /* нет сети — считаем, что не получено ничего, и спросим лишний раз */ }
  }

  /**
   * Спросить сервер, что показать после входа.
   *
   * @param {boolean} scene — нужен ли БРОСОК полноэкранной сцены. После перезагрузки
   *   страницы (F5) он не нужен: новый шанс за перезагрузку не даётся. Метка аватарки
   *   приходит всегда — она не бросок, а свойство человека и дня, и обязана вернуться
   *   в каждой вкладке и после каждой перезагрузки.
   *
   * 🔥 Метку клиент НЕ ЗАПОМИНАЕТ, и это разбор двух дефектов подряд. Сперва её вообще
   * никто не хранил, а сервер выбирал заново на каждый запрос — украшение менялось при
   * переходе между вкладками (Влад сообщил как «не снимается»). Потом её положили в
   * `localStorage`, и стало хуже: след срабатывания живёт час, токен пять, и
   * восстановленная из памяти метка след не обновляла — один неудавшийся `claim`
   * означал, что ачивку до конца дня забрать уже нечем, молча. Теперь метку каждый раз
   * даёт сервер: она одинакова весь день, а след при этом всегда свежий.
   */
  async function afterLogin(scene = true) {
    const auth = useAuthStore()
    if (auth.role !== 'student') return null
    try {
      const { data } = await easterApi.onLogin(scene ? {} : { scene: 0 })
      // ⚠️ Метка на аватарке приходит СВОИМ полем и не конкурирует с полноэкранной
      // сценой: одна перекрывает экран на секунды, вторая висит тихо, показать можно
      // и то и другое. А вот выбор ВНУТРИ пары (DOOM или Detroit) делает сервер —
      // обе рисуются на одной аватарке, и вместе дали бы кашу.
      // ⚠️ Прежде чем ставить новую, снимаем старую: без этого метка с ПРОШЛОГО входа
      // оставалась на аватарке навсегда — вышел, зашёл, а свечение всё то же.
      //Сперва снимаем прошлую метку: сервер мог выбрать другую (наступил новый день),
      //и без этого на аватарке оказались бы кольцо и свечение разом.
      easter_clearAvatar()
      if (data.avatar) place(data.avatar)
      if (data.egg) place(data.egg)
      return data.egg || null
    } catch {
      return null
    }
  }

  /**
   * Разложить выпавшую пасхалку по нужному каналу (см. IN_PAGE выше).
   *
   * ⚠️ У полноэкранной сцены заводится ПРЕДОХРАНИТЕЛЬ. Каждая сцена закрывает себя сама
   * по таймеру, и это нормально — пока таймер заводится. Но однажды он не завёлся:
   * Stanley и Far Cry раскладывали реплики по длительности mp3 и ждали `loadedmetadata`,
   * а без звука это событие не приходит никогда. Сцена оставалась «играющей» вечно, и
   * цена была не косметическая: занятый слот `active` запрещает выпадать всем остальным
   * пасхалкам до конца сессии, а подтверждение перехода (23.08.2026) спрашивало бы
   * «точно уйти?» на каждой вкладке.
   *
   * Пять минут — заведомо больше любой нашей сцены (самая длинная, ночная смена FNAF,
   * идёт около минуты) и заведомо меньше «навсегда». Предохранитель не заменяет
   * собственный таймер сцены и не должен срабатывать никогда: сработал — это дефект,
   * и он теперь виден в консоли, а не проглочен.
   */
  const STUCK_MS = 5 * 60 * 1000
  let stuckTimer = 0

  // ━━ КОРОТКИЙ ЗАМОК НА ПЕРЕХОД ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  // Наблюдение Влада: у пасхалок ДВА разных механизма, и обращаться с ними одинаково
  // неправильно. Штамп или кубик ПОЯВЛЯЮТСЯ НА странице — их легко не заметить, и
  // вопрос «останьтесь, а то не заберёте» там по делу. А дерево Делтарун или Hotline
  // ЗАМЕНЯЮТ СОБОЙ ЭКРАН: пропустить их невозможно, и вопрос «на странице что-то есть»
  // звучит нелепо — человек и так смотрит прямо на это «что-то».
  //
  // Опасен у них другой момент — ПЕРВЫЙ. Сцена возникает поверх страницы ровно тогда,
  // когда рука уже нажимает соседнюю вкладку, и находка исчезает, не успев начаться.
  // Поэтому вместо вопроса — беззвучная задержка на пару секунд сразу после появления.
  //
  // ⚠️ Задержка НЕ заменяет подтверждение целиком: когда она истекла, работает обычное
  // правило (спросить, если ачивка ещё не получена). Иначе редкую находку можно было бы
  // потерять одним случайным кликом на третьей секунде.
  const NAV_LOCK_MS = 2500
  const lockedUntil = ref(0)

  /** Идёт ли сейчас та самая пара секунд, когда уходить нельзя. */
  function navLocked() { return Date.now() < lockedUntil.value }
  function place(egg) {
    if (IN_PAGE.has(egg)) { inPage.value = { ...inPage.value, [egg]: true }; return }
    active.value = egg
    //Замок ставим ТОЛЬКО полноэкранной сцене: слой внутри страницы никому не мешает
    //уйти, и запирать навигацию из-за него значило бы наказывать за находку.
    lockedUntil.value = Date.now() + NAV_LOCK_MS
    clearTimeout(stuckTimer)
    stuckTimer = setTimeout(() => {
      if (active.value !== egg) return
      console.warn('[пасхалки] сцена не закрыла себя сама и снята предохранителем:', egg)
      active.value = ''
    }, STUCK_MS)
  }

  /** Спросить журнал: счётчик стиля отличнику и/или редкая находка. */
  async function rollJournal() {
    const auth = useAuthStore()
    if (auth.role !== 'student') return
    try {
      const { data } = await easterApi.journal()
      if (data.ultrakill) place('ultrakill_rank')
      if (data.egg) place(data.egg)
      return data
    } catch {
      return null                // нет сети — журнал просто откроется без шуток
    }
  }

  /** Показать сцену без броска — для отладки и для повторного входа в уже начатую. */
  function show(egg) { place(egg) }
  function close() { clearTimeout(stuckTimer); lockedUntil.value = 0; active.value = '' }
  /** Убрать пасхалку страницы: доиграла и больше не нужна. */
  function closeInPage(egg) {
    const next = { ...inPage.value }
    delete next[egg]
    inPage.value = next
  }

  /**
   * Есть ли прямо сейчас на экране пасхалка, которую человек рискует ПРОПУСТИТЬ,
   * уйдя со страницы. Пустая строка — нечего терять.
   */
  // ━━ НОЧНАЯ СМЕНА FNAF ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  //
  // 🔥 ЕДИНСТВЕННАЯ ПАСХАЛКА, КОТОРАЯ ЖИВЁТ ПОВЕРХ ВСЕГО САЙТА, и её состояние поэтому
  // лежит здесь, а не в компоненте сцены. Правила игры (Влад, 25.08.2026):
  //
  //   зашёл ночью  → офис;
  //   нажал ноутбук → можно ходить по вкладкам, внизу висит «в офис»;
  //   зашёл к Вектору (вкладка ИЛИ шторка) → его нет;
  //   написал вопрос → вернулся СРАЗУ В ОБОИХ местах;
  //   вернул три раза → на четвёртый приманить нельзя, скример гарантирован.
  //
  // ⚠️ Пропажа Вектора — ОДНА величина на оба места показа. Держи её в компонентах —
  // и человек, заметивший пропажу в шторке, увидел бы Вектора на вкладке живым: игра
  // развалилась бы ровно там, где в неё поверили.
  //
  // ⚠️ Ограничитель на три возврата нужен по существу, а не для строгости. Без него
  // достаточно держать вкладку Вектора открытой и отвечать на каждую пропажу, чтобы
  // ачивку не получить НИКОГДА — а выдаёт её именно скример.
  const FNAF_LURES = 3
  const fnaf = ref({ roaming: false, hidden: false, lures: 0, doomed: false })

  /** Ноутбук открыт: человек уходит гулять по сайту, Вектор пропадает. */
  function fnafRoam(on) {
    fnaf.value = { ...fnaf.value, roaming: on, hidden: on }
  }

  /**
   * Вектору задали вопрос, пока его «нет».
   * @returns {boolean} вернулся ли он. `false` — приманить больше нельзя, будет скример.
   */
  function fnafLure() {
    if (!fnaf.value.hidden) return true
    if (fnaf.value.lures >= FNAF_LURES) {
      fnaf.value = { ...fnaf.value, doomed: true }
      return false
    }
    fnaf.value = { ...fnaf.value, hidden: false, lures: fnaf.value.lures + 1 }
    return true
  }

  /** Вектор снова пропал (следующий круг игры). */
  function fnafHide() {
    if (fnaf.value.roaming) fnaf.value = { ...fnaf.value, hidden: true }
  }

  /** Ночь кончилась — во всех смыслах. */
  function fnafEnd() {
    fnaf.value = { roaming: false, hidden: false, lures: 0, doomed: false }
  }

  /**
   * Ачивка за эту пасхалку уже получена? От этого зависит РЕПЛИКА вопроса, а не сам
   * вопрос (см. `LEAVE_ASK_AGAIN`).
   *
   * 🔥 Здесь была функция `stillWorthIt`, которая вырезала полученные из `pending`
   * ЦЕЛИКОМ — то есть вопрос про них не задавался вовсе. Замысел был разумный
   * («останьтесь, а то не заберёте» бессмысленно, когда забирать нечего), но снаружи
   * это выглядело как пропавшая функция: на новом аккаунте предупреждение есть, на
   * своём нет. Влад так и сообщил — как баг.
   * Теперь спрашиваем всегда, но другими словами.
   */
  function alreadyOwned(egg) {
    const aid = EGG_ACHIEVEMENT[egg]
    return !!aid && owned.value.has(aid)
  }
  const pending = computed(() => {
    // 🔥 ИСКЛЮЧЕНИЕ ДЛЯ НОЧНОЙ СМЕНЫ. У всех остальных сцен уход со страницы означает
    // «находка потеряна», поэтому мы и переспрашиваем. У FNAF ровно наоборот: ходить
    // по вкладкам — это и есть игра. Влад поймал это живьём: открыл ноутбук, попробовал
    // перейти к Вектору, получил «точно уйти?», подтвердил — и пасхалка закрылась,
    // то есть продукт запретил единственное действие, которого сам же и ждал.
    if (active.value === 'fnaf_night_mode' && fnaf.value.roaming) return ''
    if (active.value) return active.value
    return Object.keys(inPage.value).find((k) => MISSABLE_IN_PAGE.has(k)) || ''
  })
  /** Спрашивать ли «уже было» вместо «не упустите» — для текущего `pending`. */
  const pendingOwned = computed(() => !!pending.value && alreadyOwned(pending.value))

  /**
   * Человек подтвердил, что уходит. Снимаем пропускаемую пасхалку — иначе кубик или
   * штамп уехали бы за ним на следующую страницу, где им нечего делать (штамп ищет
   * профиль, кубик — клетки оценок) и где они висели бы мёртвой картинкой.
   * ⚠️ Постоянные (кольцо, HUD, счётчик) НЕ трогаем: их не «пропускают».
   */
  function dismissPending() {
    clearTimeout(stuckTimer)
    lockedUntil.value = 0
    active.value = ''
    const next = { ...inPage.value }
    for (const k of Object.keys(next)) if (MISSABLE_IN_PAGE.has(k)) delete next[k]
    inPage.value = next
  }

  /**
   * Находка доиграна: просим сервер закрыть её ачивкой.
   * Сервер сверяет, что пасхалка ДЕЙСТВИТЕЛЬНО срабатывала у этого человека, — то есть
   * накрутить список запросом нельзя. Молча глотать отказ нельзя тоже: человек уже
   * увидел сцену и ждёт награды, поэтому тост показываем только по факту успеха.
   */
  async function claim(egg) {
    const achievement = EGG_ACHIEVEMENT[egg]
    if (!achievement) return false
    try {
      const { data } = await easterApi.claim({ egg, achievement })
      //Пополняем копию в любом случае: `unlocked=false` означает «уже была», а не отказ.
      owned.value = new Set(owned.value).add(achievement)
      if (data.unlocked) lastUnlocked.value = achievement
      return !!data.unlocked
    } catch {
      return false
    }
  }

  function clearToast() { lastUnlocked.value = null }

  /**
   * Полное обнуление при выходе из аккаунта.
   *
   * ⚠️ Без него состояние пасхалок ПЕРЕЖИВАЛО смену пользователя: на экране входа
   * всплывал тост «достижение открыто» от предыдущего человека, а список его ачивок
   * (`owned`) продолжал глушить вопросы у следующего. На общем компьютере колледжа
   * выход — это смена владельца, и всё, что помнит стор, обязано стираться; ровно тем
   * же соображением уже чистятся черновики мессенджера и оффлайн-кэш (§5.4).
   */
  function reset() {
    // 🔥 СНИМАЕМ ЗАМОК ПАСХАЛОК ВХОДА. Он ставится в оболочке ключом
    // `gb.egg.login:<логин>` и живёт в sessionStorage, то есть ПЕРЕЖИВАЕТ выход из
    // аккаунта. Из-за этого «вошёл → вышел → вошёл снова» в одной вкладке давало ровно
    // ОДИН бросок за всю её жизнь: Cyberpunk, Detroit, Skyrim и ночной FNAF после
    // первой же попытки становились недостижимы, пока вкладку не закроешь. Влад с
    // Ярославом честно пробовали и не понимали, почему ничего не выпадает.
    //
    // ⚠️ Замок нужен против F5: перезагрузка не должна давать новый шанс. Но ВЫХОД —
    // это не перезагрузка, это конец сессии человека, и следующий вход обязан быть
    // полноценным. Снимаем ключи именно здесь, в `reset()`, потому что зовётся он
    // ровно из `logout()`.
    try {
      for (let i = sessionStorage.length - 1; i >= 0; i--) {
        const k = sessionStorage.key(i)
        if (k && k.startsWith('gb.egg.login:')) sessionStorage.removeItem(k)
      }
    } catch { /* приватный режим — там замка и не было */ }

    // 🔥 ПАМЯТЬ О ВЗЯТОМ ЯЙЦЕ ДЕРЕВА УХОДИТ ВМЕСТЕ С ТОКЕНОМ (24.08.2026). Она лежит в
    // `localStorage`, то есть переживает и закрытие вкладки, и выход из аккаунта — а на
    // общем компьютере колледжа это прямо нарушает правило «выход — это смена
    // владельца».
    // ⚠️ НОВЫЕ ключи `gb.egg.tree` больше не заводятся вовсе: дерево теперь смотрит на
    // НАЛИЧИЕ АЧИВКИ, а не на память устройства (та стиралась при выходе, и диалог про
    // получение яйца начинался заново у человека, у которого яйцо давно есть). Уборку
    // оставляем, чтобы снять ключи, уже лежащие на реальных машинах.
    // ⚠️ Метки аватарки здесь НЕТ намеренно: клиент её не хранит вовсе, её каждый раз
    // выдаёт сервер (см. `afterLogin`). Достаточно очистки `inPage` ниже.
    try {
      for (let i = localStorage.length - 1; i >= 0; i--) {
        const k = localStorage.key(i)
        if (k && k.startsWith('gb.egg.tree')) localStorage.removeItem(k)
      }
    } catch { /* приватный режим — хранить было негде */ }

    clearTimeout(stuckTimer)
    //Ночная смена — тоже состояние человека, а не вкладки: на общем компьютере
    //следующий не должен обнаружить, что у него пропал Вектор.
    fnafEnd()
    active.value = ''
    lockedUntil.value = 0
    inPage.value = {}
    owned.value = new Set()
    lastUnlocked.value = null
    inFlight.clear()
  }

  return { active, inPage, owned, lastUnlocked, pending, pendingOwned, alreadyOwned, navLocked,
           fnaf, fnafRoam, fnafLure, fnafHide, fnafEnd, FNAF_LURES, roll, afterLogin, rollJournal,
           loadOwned, show, close, closeInPage, dismissPending, claim, clearToast, reset }
})
