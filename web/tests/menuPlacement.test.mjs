// menuPlacement.test.mjs — меню сообщения обязано целиком помещаться в окно.
//
// Живая жалоба Влада (05.09.2026): «вылазит меню, но она уезжает за край окна если
// сообщение внизу». Причина была в числе, вписанном руками: высота меню объявлялась
// константой 360, а собирается оно из пунктов по правам плюс две строки реакций и гуляет
// вдвое. Здесь проверяется СВОЙСТВО «меню в окне», а не конкретное число.
//
// Обратный ход (проверен): вернуть в `placeMenu` формулу `top = Math.min(y, vh - 360)` —
// краснеет «меню у нижнего края разворачивается вверх» на любом меню выше 360.
import test from 'node:test'
import assert from 'node:assert/strict'
import { EDGE, menuMaxHeight, placeAnchored, placeMenu } from '../src/utils/menuPlacement.js'

const VW = 1200
const VH = 800

test('обычный случай: меню открывается ВНИЗ от точки нажатия', () => {
  // Вниз — чтобы меню не закрывало то, по чему нажали.
  const r = placeMenu({ x: 300, y: 100, w: 240, h: 400, vw: VW, vh: VH })
  assert.equal(r.placement, 'down')
  assert.equal(r.top, 100)
  assert.equal(r.left, 300)
})

test('у нижнего края меню разворачивается ВВЕРХ, а не обрезается', () => {
  // Ровно жалоба: сообщение внизу ленты, места вниз нет никогда.
  const h = 420
  const r = placeMenu({ x: 300, y: 760, w: 240, h, vw: VW, vh: VH })
  assert.equal(r.placement, 'up')
  assert.ok(r.top >= 0, 'меню уехало за верхний край')
  assert.ok(r.top + h <= 760, 'развёрнутое вверх меню обязано кончаться выше точки нажатия')
})

test('меню целиком в окне при ЛЮБОЙ высоте и точке нажатия', () => {
  // Свойство, а не набор случаев: именно его и нарушала константа 360.
  for (const h of [120, 260, 360, 420, 560, 700]) {
    for (let y = 0; y <= VH; y += 40) {
      const r = placeMenu({ x: 600, y, w: 240, h, vw: VW, vh: VH })
      assert.ok(r.top >= 0, `top=${r.top} при h=${h}, y=${y}`)
      assert.ok(r.top + h <= VH || h + EDGE * 2 > VH,
        `меню (h=${h}) вылезло за низ при y=${y}: top=${r.top}`)
    }
  }
})

test('меню выше самого окна прижимается к верху, а не режется снизу', () => {
  // Внизу списка лежат «Удалить» и «Пожаловаться» — то есть ровно те пункты, ради
  // которых меню и открывают. Обрезать их нельзя; за помещаемость отвечает прокрутка,
  // и её предел даёт menuMaxHeight.
  const r = placeMenu({ x: 100, y: 400, w: 240, h: 2000, vw: VW, vh: VH })
  assert.equal(r.top, EDGE)
  assert.ok(menuMaxHeight(VH) <= VH - EDGE * 2)
})

test('по горизонтали меню тоже не уезжает', () => {
  const r = placeMenu({ x: VW - 10, y: 100, w: 240, h: 200, vw: VW, vh: VH })
  assert.ok(r.left + 240 <= VW, 'меню вылезло за правый край')
  const l = placeMenu({ x: -50, y: 100, w: 240, h: 200, vw: VW, vh: VH })
  assert.ok(l.left >= 0, 'меню вылезло за левый край')
})

test('на узком телефоне в альбомной ориентации меню не исчезает', () => {
  // vh=320: не помещается ни вниз, ни вверх — но должно быть видно хоть что-то.
  const r = placeMenu({ x: 200, y: 300, w: 240, h: 400, vw: 640, vh: 320 })
  assert.ok(r.top >= 0 && r.top < 320)
  assert.ok(menuMaxHeight(320) >= 120, 'предел высоты не должен схлопывать меню в ничто')
})

// ── Меню, привязанное к КНОПКЕ (меню доступности) ──────────────────────────────────
const btn = (top, h = 36) => ({ top, bottom: top + h, left: 1100, right: 1160 })

test('привязанное меню открывается туда, куда просили, если помещается', () => {
  const up = placeAnchored({ anchor: btn(600), w: 260, h: 200, vw: VW, vh: VH, prefer: 'up' })
  assert.equal(up.placement, 'up')
  assert.ok(up.top + 200 <= 600, 'меню обязано кончаться НАД кнопкой')
})

test('у верхней кромки меню не уезжает за экран — это и был дефект', () => {
  // В AccessibilityMenu стоял комментарий «вылезло за край — прижимаем», а прижималась
  // только горизонталь: меню, открытое вверх от кнопки в шапке, уходило за верх целиком.
  const r = placeAnchored({ anchor: btn(20), w: 260, h: 400, vw: VW, vh: VH, prefer: 'up' })
  assert.ok(r.top >= 0, `меню уехало вверх: top=${r.top}`)
  assert.equal(r.placement, 'down', 'вверх не помещается — обязано открыться вниз')
})

test('привязанное меню целиком в окне при любой высоте кнопки', () => {
  for (const h of [120, 300, 500]) {
    for (let top = 0; top <= VH - 36; top += 40) {
      const r = placeAnchored({ anchor: btn(top), w: 260, h, vw: VW, vh: VH, prefer: 'up' })
      assert.ok(r.top >= 0, `top=${r.top} при h=${h}`)
      assert.ok(r.top + h <= VH || h + EDGE * 2 > VH, `вылезло вниз при h=${h}, top=${top}`)
    }
  }
})

test('правый край меню равняется по кнопке и не вылезает за окно', () => {
  const r = placeAnchored({ anchor: btn(100), w: 260, h: 200, vw: VW, vh: VH })
  assert.ok(r.left >= EDGE && r.left + 260 <= VW)
})

