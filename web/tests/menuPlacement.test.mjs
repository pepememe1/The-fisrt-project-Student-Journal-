//
// Облачко форматирования над выделенным текстом в композере вписывало СВОЮ ШИРИНУ
// числом: `const half = 96`, то есть 192 px. Число неверно по построению — кнопок в
// облачке столько, сколько разметок мы поддерживаем, и добавление одной делает его шире,
// а кламп продолжает считать по-старому. Ровно то же, за что чинили меню сообщения
// (`Math.min(y, innerHeight - 360)`) и меню журнала (кламп по горизонтали числом 200).
import { readFileSync as _read } from 'node:fs'

test('облачко форматирования ИЗМЕРЯЕТСЯ, а не объявляет свой размер числом', () => {
  const chat = _read(new URL('../src/components/messenger/ChatThread.vue', import.meta.url), 'utf8')
  const fn = chat.match(/function clampFmtBubble\(\)[\s\S]*?\n\}/)?.[0] || ''
  assert.ok(fn, 'не нашли clampFmtBubble — облачко снова считает положение на глазок')
  assert.ok(/offsetWidth/.test(fn), 'ширина облачка не измеряется')
  assert.ok(!/=\s*\d{2,}\s*$/m.test(fn.replace(/\/\/.*$/gm, '')),
    'в расчёте облачка снова появилось вписанное число размера')
  assert.ok(/window\.innerWidth/.test(fn),
    'облачко вписывается в обёртку, а не в окно — на узком экране это не спасает')
})

test('просвет от края у всплывающих слоёв ОДИН', () => {
  // Два разных отступа у двух соседних слоёв читаются как небрежность, а не решение.
  const chat = _read(new URL('../src/components/messenger/ChatThread.vue', import.meta.url), 'utf8')
  assert.ok(/import \{ EDGE \} from '@\/utils\/menuPlacement'/.test(chat),
    'облачко завело свой отступ от края вместо общего EDGE')
})
