// markupSpans.test.mjs — приглушение символов разметки в поле ввода (как в Discord).
//
// Просьба Влада (05.09.2026): «если с обоих сторон текста есть совпадающие символы
// которые его форматируют, сделай их полупрозрачными, как в дискорд». На присланном
// снимке строка `*фаыфа* *вфввв`: у ЗАКРЫТОЙ пары звёздочки приглушены, у незакрытой —
// обычные, потому что форматированием она пока не является.
//
// Обратный ход (проверен): убрать в `markupSpans` проверку «нашлась закрывающая» —
// краснеет «незакрытая обёртка остаётся обычным текстом»; убрать сортировку PAIRS по
// длине — краснеет «жирный не разбирается как два курсива».
import test from 'node:test'
import assert from 'node:assert/strict'
import { markupSpans, selectionWrapped, toggleWrap } from '../src/utils/markupSpans.js'

const dimmed = (s) => markupSpans(s).filter((p) => p.dim).map((p) => p.text)
const joined = (s) => markupSpans(s).map((p) => p.text).join('')

test('закрытая пара приглушается, текст между ней — нет', () => {
  const spans = markupSpans('*курсив*')
  assert.deepEqual(spans, [
    { text: '*', dim: true },
    { text: 'курсив', dim: false },
    { text: '*', dim: true },
  ])
})

test('незакрытая обёртка остаётся обычным текстом', () => {
  // Ровно случай со снимка Discord: пока вторая звёздочка не набрана, форматирования
  // нет, и обещать его приглушением нельзя.
  assert.deepEqual(dimmed('*вфввв'), [])
})

test('строка со снимка разбирается как на снимке', () => {
  // `*фаыфа* *вфввв` — первая пара закрыта, вторая нет.
  assert.deepEqual(dimmed('*фаыфа* *вфввв'), ['*', '*'])
})

test('жирный не разбирается как два курсива', () => {
  // Порядок в PAIRS значим: длинные маркеры проверяются раньше коротких.
  assert.deepEqual(dimmed('**жирный**'), ['**', '**'])
})

test('пустая пара — это два обычных символа, а не пустой курсив', () => {
  assert.deepEqual(dimmed('**'), [])
})

test('разбор НИЧЕГО не теряет и ничего не добавляет', () => {
  // Зеркало рисует текст поверх настоящего поля: потеря или лишний символ сдвинули бы
  // всю строку, и приглушённые символы съехали бы с настоящих.
  for (const s of ['', 'обычный текст', '*a* **b** ~~c~~ `d` __e__', '***', 'a*b*c', '**a`b`c**']) {
    assert.equal(joined(s), s, `потеря символов на «${s}»`)
  }
})

test('selectionWrapped видит обёртку и ВНУТРИ, и ВМЕСТЕ с ней', () => {
  // Мышь цепляет края по-разному, а кнопка облачка обязана показывать одно и то же
  // состояние на одном и том же жирном тексте.
  const inside = '**жирный**'
  assert.equal(selectionWrapped(inside, 2, 8, '**'), true, 'выделено внутри обёрток')
  assert.equal(selectionWrapped(inside, 0, 10, '**'), true, 'выделено вместе с обёртками')
  assert.equal(selectionWrapped('обычный', 0, 7, '**'), false)
})

test('кнопка ПЕРЕКЛЮЧАЕТ: второе нажатие снимает обёртку', () => {
  // Иначе повтор давал бы ****жирный****, и починить это можно было бы только руками —
  // то есть кнопка, которой нельзя отменить саму себя.
  const on = toggleWrap('жирный', 0, 6, '**')
  assert.equal(on.text, '**жирный**')
  assert.deepEqual([on.start, on.end], [2, 8])

  const off = toggleWrap(on.text, on.start, on.end, '**')
  assert.equal(off.text, 'жирный')
  assert.deepEqual([off.start, off.end], [0, 6])
})

test('снятие работает и когда обёртки попали В выделение', () => {
  const off = toggleWrap('**жирный**', 0, 10, '**')
  assert.equal(off.text, 'жирный')
})

test('границы выделения переживают обёртывание', () => {
  // Без возврата границ курсор прыгал бы в конец после каждой кнопки, и вторую подряд
  // (жирный + курсив) поставить было бы нельзя.
  const src = 'до слово после'
  const r = toggleWrap(src, 3, 8, '*')
  assert.equal(r.text.slice(r.start, r.end), 'слово')
})
