// highlightFragment.test.mjs — поиск процитированного куска в теле сообщения.
//
// Просьба Влада (05.09.2026): «при нажатии [на цитату] перекинет к выделенному фрагменту
// и подсветит его». Тело сообщения — HTML после Markdown-lite, и искомая фраза почти
// всегда разорвана тегами (`<strong>`, `<a>`, `<br>`). Поэтому ищем по ТЕКСТОВЫМ УЗЛАМ, а
// арифметика «в каком узле и с какого смещения» проверяется здесь, без браузера.
//
// Обратный ход (проверен): убрать нормализацию пробелов — краснеет «фраза через перенос
// строки»; искать в склеенной строке без карты позиций — краснеет «двойной пробел не
// сдвигает координаты».
import test from 'node:test'
import assert from 'node:assert/strict'
import { findFragment, flatten } from '../src/utils/highlightFragment.js'

test('фраза в одном узле находится с точными координатами', () => {
  const r = findFragment(['первая строка вторая строка'], 'вторая')
  assert.deepEqual(r, { start: { index: 0, offset: 14 }, end: { index: 0, offset: 20 } })
})

test('фраза, разорванная тегами, всё равно находится', () => {
  // Так выглядит «очень важно» в `очень <strong>важно</strong>`: два текстовых узла.
  const r = findFragment(['очень ', 'важно', ' дальше'], 'очень важно')
  assert.equal(r.start.index, 0)
  assert.equal(r.start.offset, 0)
  assert.equal(r.end.index, 1)
  assert.equal(r.end.offset, 5)
})

test('фраза через перенос строки — честная', () => {
  // Выделение мышью браузер отдаёт с пробелом вместо переноса. Точное совпадение не
  // нашлось бы у совершенно нормальной цитаты, и переход выглядел бы сломанным.
  const r = findFragment(['Первая строка\nвторая строка'], 'строка вторая')
  assert.ok(r, 'фраза через перенос не найдена')
})

test('двойной пробел не сдвигает подсветку', () => {
  // Нормализация меняет ДЛИНУ строки; без карты позиций подсветка уехала бы вбок ровно
  // на число схлопнутых пробелов.
  const src = 'слово  другое'
  const r = findFragment([src], 'другое')
  assert.equal(src.slice(r.start.offset, r.end.offset), 'другое')
})

test('отсутствующая фраза даёт null, а не случайное место', () => {
  // Оригинал могли отредактировать после ответа. Вызывающий тогда подсвечивает всё
  // сообщение целиком — перемотка всё равно привела туда, куда обещала.
  assert.equal(findFragment(['какой-то текст'], 'совсем другое'), null)
  assert.equal(findFragment(['текст'], '   '), null)
  assert.equal(findFragment([], 'что-нибудь'), null)
})

test('flatten приводит пробелы к одному виду — как проверка цитаты на сервере', () => {
  // Правила по обе стороны обязаны совпадать: разойдутся — сервер цитату примет, а
  // подсветка её «не найдёт», и это будет выглядеть как сломанный переход.
  assert.equal(flatten('а\nб\tв   г'), 'а б в г')
})
