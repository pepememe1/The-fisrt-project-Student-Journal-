// groupSearch.test.mjs — поиск группы по названию.
//
// Проверяются ЖИВЫЕ имена с портала («К74/1», «К74/3,75.0» → «К75.0», «316-1 ЭиЭ»), а не
// удобные выдуманные: правило целиком про то, как человек ПРОМАХИВАЕТСЯ мимо точного
// написания, и на ровных данных оно зелено всегда.
//
// ⚠️ Тест зовёт функции ПРОДУКТА, а не повторяет формулу у себя: копия, сверяемая с
// копией, не покраснеет ни на одной правке (§«сторож, который не может покраснеть»).
import test from 'node:test'
import assert from 'node:assert/strict'
import { filterGroups, groupMatchRank, normalizeGroup, compactGroup, toRussianLayout }
  from '../src/utils/groupSearch.js'

// Живой срез: колледж («К»), бакалавриат с хвостом специальности, составные номера.
const LIVE = ['К74/1', 'К74/3', 'К75.0', 'К15.0', 'К7', '316-1 ЭиЭ', '545 исит', 'М12']

test('«к» и «К» дают одни и те же группы — прямое требование', () => {
  const lower = filterGroups(LIVE, 'к')
  const upper = filterGroups(LIVE, 'К')
  assert.deepEqual(lower, upper)
  assert.ok(lower.length > 0, 'группы на «К» обязаны находиться')
  assert.ok(lower.every((g) => g.startsWith('К')), `в выдаче чужие: ${lower.join(', ')}`)
  assert.ok(!lower.includes('М12'), 'группа не на «К» не имеет права попасть в выдачу')
})

test('латинская «k» — та же выдача: имя ПЕРЕПИСАЛИ латиницей', () => {
  // Начертание: «K74/1» вместо «К74/1». Так группы попадают в переписку и в документы.
  assert.deepEqual(filterGroups(LIVE, 'k'), filterGroups(LIVE, 'к'))
  assert.deepEqual(filterGroups(LIVE, 'K'), filterGroups(LIVE, 'К'))
})

test('«r» — та же выдача: НЕ ПЕРЕКЛЮЧИЛИ РАСКЛАДКУ, и это другая клавиша', () => {
  // 🔥 ЗДЕСЬ БЫЛО НЕВЕРНОЕ УТВЕРЖДЕНИЕ, и его нашёл разбор, а не прогон. Тест назывался
  // «не переключил раскладку», а проверял `k` — то есть НАЧЕРТАНИЕ. На ЙЦУКЕН русская
  // «К» лежит на клавише `r`: человек, знающий свою группу пальцами, печатает «r74/1»,
  // получал пустой список, а комментарий уверял, что случай закрыт.
  assert.equal(toRussianLayout('r74/1'), 'к74/1')
  assert.deepEqual(filterGroups(LIVE, 'r'), filterGroups(LIVE, 'к'))
  assert.deepEqual(filterGroups(LIVE, 'r74/1'), ['К74/1'])
  assert.deepEqual(filterGroups(LIVE, 'r74'), ['К74/1', 'К74/3'])
})

test('два прочтения запроса не мешают друг другу', () => {
  // Карты конфликтуют на одной букве: `k` по начертанию «к», по клавише «л». Выбрать за
  // человека нельзя — пробуем оба прочтения и берём лучшее.
  assert.equal(normalizeGroup('k'), 'к')
  assert.equal(toRussianLayout('k'), 'л')
  assert.ok(filterGroups(LIVE, 'k').length > 0, 'прочтение по начертанию потерялось')
  // Бессмысленный набор не обязан находить ничего: «rfr» это «как», такой группы нет.
  assert.deepEqual(filterGroups(LIVE, 'rfr'), [])
})

test('запасной ход по цифрам НЕ отбрасывает буквы запроса', () => {
  // 🔥 Пока цифровой ход работал на любом запросе, «к9» возвращало К19, К29, К39:
  // буквенная часть отбрасывалась целиком, и человек получал не свою группу, а всё с
  // девяткой внутри. Набрал букву — значит имел её в виду.
  assert.deepEqual(filterGroups(['К19', 'К29', 'К9'], 'к9'), ['К9'])
  assert.deepEqual(filterGroups(['К19', 'К29'], 'к9'), [])
  // А чисто цифровой запрос по-прежнему ищет по цифрам.
  assert.deepEqual(filterGroups(['К19', 'К29'], '9'), ['К19', 'К29'])
})

test('поиск по цифрам находит группу, даже когда разделитель забыт', () => {
  assert.deepEqual(filterGroups(LIVE, '74'), ['К74/1', 'К74/3'])
  // «741» подстрокой в «К74/1» НЕ входит — находит только сжатая форма. Ради этого
  // случая правило и заводилось: разделитель («/», «.», «-») человек помнит последним.
  assert.deepEqual(filterGroups(LIVE, '741'), ['К74/1'])
  assert.deepEqual(filterGroups(LIVE, '316'), ['316-1 ЭиЭ'])
  assert.deepEqual(filterGroups(LIVE, '75.0'), ['К75.0'])
})

test('точное совпадение стоит выше частичного', () => {
  // Иначе «К7» тонет среди К74/1, К74/3, К75.0 — ровно то, ради чего открывали поиск.
  assert.equal(filterGroups(LIVE, 'К7')[0], 'К7')
  assert.ok(groupMatchRank('К7', 'К7') < groupMatchRank('К74/1', 'К7'))
})

test('пустой запрос показывает всё и НЕ переставляет порядок портала', () => {
  // Свой алфавитный порядок поверх чужого читается как перетасовка: человек ищет группу
  // там, где видел её в прошлый раз.
  assert.deepEqual(filterGroups(LIVE, ''), LIVE)
  assert.deepEqual(filterGroups(LIVE, '   '), LIVE)
})

test('запрос, которому никто не отвечает, даёт пустоту, а не весь список', () => {
  // Показать всё при непонятном запросе — худший исход: человек решит, что фильтр
  // сработал, и станет искать свою группу глазами в полном списке.
  assert.deepEqual(filterGroups(LIVE, 'zzz'), [])
  assert.equal(groupMatchRank('К74/1', 'zzz'), -1)
})

test('нормализация применяется к ОБЕИМ сторонам', () => {
  // Односторонняя (только к запросу) разошлась бы на первом же названии с необычным
  // написанием: человек видит группу в списке, вводит ровно то, что видит, и не находит.
  assert.equal(normalizeGroup('  К74/1  '), 'к74/1')
  assert.equal(normalizeGroup('K74/1'), 'к74/1')          //латинская K
  assert.equal(compactGroup('К74/1'), 'к741')
  assert.equal(compactGroup('316-1 ЭиЭ'), '3161эиэ')
})

test('обратный ход: без карты начертаний тест обязан краснеть', () => {
  // Сторож, который зелен и без починки, неотличим от исправного кода. Здесь дефект
  // воспроизводится дословно — «сравниваем как есть, раскладку не учитываем».
  const naive = (names, q) => names.filter((n) => n.toLowerCase().includes(q.toLowerCase()))
  assert.deepEqual(naive(LIVE, 'k'), [], 'латинская k на живых данных не находит НИЧЕГО')
  assert.notDeepEqual(naive(LIVE, 'k'), filterGroups(LIVE, 'k'))
  assert.deepEqual(naive(LIVE, 'r'), [], 'и клавиша русской «К» тоже не находит НИЧЕГО')
  assert.notDeepEqual(naive(LIVE, 'r'), filterGroups(LIVE, 'r'))
  // И вторая половина дефекта — цифры без учёта разделителя.
  assert.deepEqual(naive(LIVE, '741'), [])
  assert.deepEqual(filterGroups(LIVE, '741'), ['К74/1'])
})
