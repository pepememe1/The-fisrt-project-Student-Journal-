// draftSync.test.mjs — «черновик догоняет сохранённое, пока его не тронули».
//
// Живая жалоба Влада (06.09.2026): «иногда при выходе вылазит окошко „точно хотите выйти
// не подтвердив действия", кнопки отмены или сохранения ни на что не влияют».
//
// Причина была ГОНКОЙ: сторож в вотчере читал `bioDirty`, а тот считается по УЖЕ НОВОМУ
// сохранённому значению. В момент прихода настроек с сервера (после монтирования
// карточки) условие всегда ложно — черновик оставался пустым, «правка» горела вечно, а
// кнопка «Сохранить» уезжала с ПУСТЫМ bio и стирала настоящий текст «о себе».
//
// Обратный ход (проверен): сравнить в `shouldFollow` черновик с НОВЫМ значением вместо
// метки — краснеет «пришедшее с сервера значение подхватывается».
import test from 'node:test'
import assert from 'node:assert/strict'
import { resetDraft, shouldFollow, syncDraft } from '../src/utils/draftSync.js'

test('пришедшее с сервера значение подхватывается, если поле не трогали', () => {
  // Ровно тот случай, что был сломан: карточка смонтировалась с пустым черновиком,
  // настройки приехали позже.
  const s0 = { draft: '', lastSynced: '' }
  const s1 = syncDraft(s0, 'о себе с сервера')
  assert.equal(s1.draft, 'о себе с сервера')
  assert.equal(s1.lastSynced, 'о себе с сервера')
})

test('начатая человеком правка НЕ затирается приходом с сервера', () => {
  // Вторая половина правила, и она не менее важна: иначе редактирование сбрасывалось бы
  // под руками на каждом обновлении настроек.
  const s0 = { draft: 'я печатаю', lastSynced: 'старое' }
  const s1 = syncDraft(s0, 'новое с сервера')
  assert.equal(s1.draft, 'я печатаю', 'правку затёрли')
  assert.equal(s1.lastSynced, 'новое с сервера', 'метка обязана двигаться всегда')
})

test('метка двигается даже когда черновик не трогали — иначе он «залипает» навсегда', () => {
  // Не сдвинь метку — следующее сравнение пойдёт с устаревшим значением, черновик
  // перестанет догонять сохранённое, и «есть несохранённые изменения» загорится само.
  let s = { draft: 'я печатаю', lastSynced: 'A' }
  s = syncDraft(s, 'B')
  s = syncDraft(s, 'C')
  assert.equal(s.lastSynced, 'C')
  // Человек нажал «Отменить» — черновик и метка обязаны сойтись.
  s = resetDraft('C')
  assert.deepEqual(s, { draft: 'C', lastSynced: 'C' })
  // И теперь следующее обновление снова подхватывается.
  assert.equal(syncDraft(s, 'D').draft, 'D')
})

test('после «Отменить» правка не воскресает', () => {
  // Отмена, не двигающая метку, — вторая форма того же дефекта: черновик равен
  // сохранённому, а метка отстала, и первое же обновление разводит их снова.
  let s = { draft: 'черновик', lastSynced: 'сохранённое' }
  s = resetDraft('сохранённое')
  assert.equal(s.draft, 'сохранённое')
  s = syncDraft(s, 'пришло новое')
  assert.equal(s.draft, 'пришло новое', 'после отмены черновик обязан догонять сервер')
})

test('shouldFollow сравнивает с МЕТКОЙ, а не с новым значением', () => {
  // Дословный обратный ход: сравнение с новым значением объявляет правкой ЛЮБОЕ
  // изменение, пришедшее с сервера, — это и был дефект.
  assert.equal(shouldFollow('', ''), true, 'нетронутое поле обязано догонять')
  assert.equal(shouldFollow('я печатаю', 'старое'), false, 'тронутое поле трогать нельзя')
})

test('пустое сохранённое значение — обычный случай, а не признак правки', () => {
  // У человека без «о себе» черновик и сохранённое пусты; загоревшаяся «правка» здесь
  // означала бы вопрос «сохранить?» при каждом уходе со страницы.
  const s = syncDraft({ draft: '', lastSynced: '' }, '')
  assert.equal(s.draft, '')
  assert.equal(shouldFollow(s.draft, s.lastSynced), true)
})
