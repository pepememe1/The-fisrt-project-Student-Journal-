/**
 * mobileLayout.test.mjs — статический сторож мобильной вёрстки.
 *
 * ━━ ЗАЧЕМ ━━
 * Живую проверку в браузере на машине разработки вести нельзя (dev-browser трижды
 * вешал компьютер, см. правило в заметках команды), а `npm run build` и обычные тесты
 * раскладку не видят вовсе: сломанная сетка собирается зелёной. Между «смотреть
 * глазами» и «не проверять никак» есть третий путь — проверять по разметке те виды
 * поломок, которые ОДНОЗНАЧНО определяются текстом класса, без рендера.
 *
 * Здесь ровно такие проверки, и намеренно НИ ОДНОЙ про «красиво». Всё, что ловится
 * ниже, даёт одно и то же наблюдаемое следствие: горизонтальную прокрутку страницы на
 * телефоне. Она в этом продукте считается дефектом — половина пользователей заходит с
 * телефона, а уехавшую вбок таблицу на 360 px не видно вовсе.
 *
 * ⚠️ Порог ложных срабатываний важнее полноты (то же правило, что у подтверждения
 * опасных команд и у порога риска отчисления): сторож, который ругается на каждую
 * вторую страницу, перестают читать, и тогда он не поймает настоящую поломку. Поэтому
 * проверок мало, и каждая — про физически невозможное на узком экране, а не про вкус.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const SRC = new URL('../src', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')

/** Самый узкий поддерживаемый экран. 360 px — не абстракция, а реальный минимум,
 *  на котором продукт проверяли: ниже него в ходу практически ничего нет. */
const NARROW = 360

function vueFiles(dir = SRC, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) vueFiles(p, out)
    else if (name.endsWith('.vue')) out.push(p)
  }
  return out
}

const FILES = vueFiles().map((p) => ({ path: p, rel: relative(SRC, p), text: readFileSync(p, 'utf8') }))

/**
 * Разбирает `class="…"` в НАБОР ТОКЕНОВ, а не ищет подстроку.
 *
 * ⚠️ Так и надо, и вот почему. Первая версия проверки ниже искала `grid` регуляркой
 * `class="[^"]*(?:^|\s)grid(?:\s|")` — и была ЗЕЛЁНОЙ, потому что не находила ничего
 * вообще: перед `grid` в `class="grid gap-6 …"` стоит кавычка, а не пробел и не начало
 * строки. Сторож, который никогда не срабатывает, неотличим от исправного кода — и это
 * хуже отсутствия сторожа, потому что создаёт ложную уверенность. Отсюда правило файла:
 * КАЖДОЕ правило обязано иметь самопроверку на заведомо плохом образце (тесты в конце).
 *
 * Классы часто перенесены на 2-3 строки, поэтому элемент собирается из окна строк.
 */
function elements(text) {
  const lines = text.split('\n')
  const out = []
  lines.forEach((line, i) => {
    // ⚠️ Сначала пробуем ЗАКРЫТЫЙ атрибут на этой же строке и только потом — перенос.
    // Первая версия дописывала следующие две строки ВСЕГДА, и вложенная сетка снизу
    // («grid-cols-3» у дочернего элемента) выглядела как базовая колонка родителя —
    // нарушение маскировалось и молча не попадало в отчёт.
    const closed = /class="([^"]*)"/.exec(line)
    let raw
    if (closed) {
      raw = closed[1]
    } else {
      const open = /class="([^"]*)$/.exec(line)
      if (!open) return
      const tail = lines.slice(i + 1, i + 4).join(' ')
      raw = `${open[1]} ${tail.split('"')[0]}`     // добираем до закрывающей кавычки
    }
    out.push({ line: i + 1, tokens: raw.split(/\s+/).filter(Boolean), raw })
  })
  return out
}

/** Сетка без базовой колонки: раскладка объявлена только с брейкпоинта. */
function gridWithoutBaseColumns(el) {
  if (!el.tokens.includes('grid')) return false
  const hasBreakpointCols = el.tokens.some((t) => /^(?:sm|md|lg|xl|2xl):grid-cols-/.test(t))
  const hasBaseCols = el.tokens.some((t) => /^grid-cols-/.test(t))
  return hasBreakpointCols && !hasBaseCols
}

test('таблица всегда лежит в контейнере с горизонтальной прокруткой', () => {
  // Таблица журнала шире экрана ВСЕГДА (столбец на занятие), и это нормально —
  // ненормально, когда вбок уезжает вся страница вместе с ней.
  // ⚠️ Прокручиваемых обёрток теперь ДВЕ, и обе настоящие: голый `overflow-x-auto` и
  // `StickyXScroll` (у него прокрутка на теле, а полоса вынесена к низу экрана —
  // 12.09.2026). Проверять надо СВОЙСТВО «таблица в прокручиваемом контейнере», а не имя
  // одного класса: иначе сторож требует вернуть неудобную прокрутку ради своей формулы.
  const scrolls = (f) => f.text.includes('overflow-x') || f.text.includes('<StickyXScroll')
  const bad = FILES.filter((f) => f.text.includes('<table') && !scrolls(f))
  assert.deepEqual(bad.map((f) => f.rel), [],
    'таблица без горизонтальной прокрутки утащит вбок всю страницу на телефоне')
})

test('жёсткая ширина шире узкого экрана — только внутри прокручиваемого контейнера', () => {
  // `min-w-[820px]` у сетки расписания законен: он лежит в `overflow-x-auto`, и вбок
  // едет ОН, а не страница. Тот же класс без такой обёртки — гарантированная поломка.
  const offenders = []
  for (const f of FILES) {
    // ⚠️ `max-` отсекается ЯВНО, а не границей слова `\b`: между дефисом и `w` она
    // срабатывает, и `max-w-[1700px]` (безобидное ограничение сверху) прилетал в
    // нарушения наравне с настоящей жёсткой шириной. Поймано первым же прогоном —
    // сторож начал с двух ложных обвинений, что как раз и обесценивает сторожей.
    for (const m of f.text.matchAll(/(^|[\s"])((?:min-)?w)-\[(\d{3,4})px\]/g)) {
      if (Number(m[3]) <= NARROW) continue
      // ⚠️ `StickyXScroll` — ТОЖЕ прокручиваемый контейнер, просто свой (12.09.2026).
      // Внутри него `overflow-x-auto` стоит на теле, а полоса прокрутки вынесена вниз
      // экрана. Без этой строки сторож краснел на КАЖДОЙ таблице, переведённой на него,
      // то есть требовал вернуть неудобную прокрутку ради формулировки проверки.
      const scrollable = f.text.includes('overflow-x') || f.text.includes('<StickyXScroll')
      if (!scrollable) offenders.push(`${f.rel}: ${m[2]}-[${m[3]}px]`)
    }
  }
  assert.deepEqual(offenders, [],
    'фиксированная ширина больше 360px вне прокручиваемого контейнера')
})

test('сетка на четыре колонки и шире обязана схлопываться на телефоне', () => {
  // Четыре колонки на 360 px — это 80 px на карточку вместе с отступами: туда не
  // помещается даже двузначное число с подписью. Две и три ещё читаются, поэтому
  // порог именно 4, а не «любая сетка».
  const offenders = []
  for (const f of FILES) {
    for (const m of f.text.matchAll(/class="([^"]*)"/g)) {
      const cls = m[1]
      const base = cls.match(/(?:^|\s)grid-cols-(\d+)/)
      if (!base || Number(base[1]) < 4) continue
      if (!/\b(sm|md|lg|xl):grid-cols-/.test(cls)) offenders.push(`${f.rel}: grid-cols-${base[1]}`)
    }
  }
  assert.deepEqual(offenders, [],
    'сетка от четырёх колонок без брейкпоинта — на телефоне колонка уже 80px')
})

test('сетка с колонками только на брейкпоинте обязана задать колонку и на телефоне', () => {
  // 🔥 САМЫЙ ДОРОГОЙ ИЗ ЗДЕШНИХ ДЕФЕКТОВ, и предыдущая версия сторожа его не видела.
  // `class="grid gap-6 lg:grid-cols-[...]"` на узком экране не имеет НИ ОДНОЙ явной
  // колонки — браузер заводит неявную дорожку размера `auto`. Такая дорожка обязана
  // вместить минимальный размер содержимого, поэтому один неразрывный кусок шире экрана
  // (длинная ссылка, слитный перечень предметов в тексте с сервера) растягивает не себя,
  // а ВСЮ КОЛОНКУ — вместе с соседними карточками, таблицами и списками, которые сами по
  // себе совершенно исправны. Симптом обманчив: «поехало» выглядит там, куда виноватый
  // текст даже не входит. Лечится одним классом: `grid-cols-1` разворачивается в
  // `minmax(0, 1fr)`, где нижняя граница НОЛЬ, и колонка физически не может стать шире
  // контейнера.
  const offenders = []
  for (const f of FILES) {
    for (const el of elements(f.text)) {
      if (gridWithoutBaseColumns(el)) offenders.push(`${f.rel}:${el.line}`)
    }
  }
  assert.deepEqual(offenders, [],
    'у сетки нет колонки на телефоне: неявная дорожка auto растянет её под самый широкий кусок')
})

test('самопроверка: правило про сетку СРАБАТЫВАЕТ на разметке, которая и вызвала баг', () => {
  // Обратный тест. Без него правило выше может быть зелёным просто потому, что ничего не
  // находит — так и случилось при первом заходе (регулярка не пропускала кавычку перед
  // `grid`). Образец — ДОСЛОВНАЯ строка «Главной» студента до починки.
  const bad = '  <div class="grid gap-6 lg:grid-cols-[minmax(190px,240px)_1fr] xl:grid-cols-[minmax(300px,380px)_1fr]">'
  const good = '  <div class="grid grid-cols-1 gap-6 lg:grid-cols-[minmax(190px,240px)_1fr]">'
  const neutral = '  <button class="grid size-7 place-items-center rounded-md">'   // сетка-иконка, не раскладка
  assert.equal(elements(bad).some(gridWithoutBaseColumns), true, 'правило обязано ловить сетку без базовой колонки')
  assert.equal(elements(good).some(gridWithoutBaseColumns), false, 'починенная разметка не должна считаться нарушением')
  assert.equal(elements(neutral).some(gridWithoutBaseColumns), false, 'grid для центрирования иконки — не раскладка')
})

test('журнал студента и родителя не прячет оценку за горизонтальной прокруткой', () => {
  // Таблица из четырёх колонок в `overflow-x-auto` формально «не ломает страницу», но на
  // 360 px за правым краем оказывается ОЦЕНКА — то единственное, ради чего журнал и
  // открывают. Студент и родитель — как раз те роли, что заходят с телефона (админ и
  // преподаватель работают за столом), поэтому правило намеренно узкое: таблица в ИХ
  // разделах обязана иметь мобильную альтернативу (`sm:block` + отдельный список).
  const offenders = []
  for (const f of FILES) {
    if (!/^pages[\\/](student|parent)[\\/]/.test(f.rel)) continue
    if (!f.text.includes('<table')) continue
    if (!/hidden[^"]*sm:block|sm:hidden/.test(f.text)) offenders.push(f.rel)
  }
  assert.deepEqual(offenders, [],
    'таблица в кабинете студента/родителя без мобильной раскладки прячет оценку за краем экрана')
})

test('длинное имя в строке обязано иметь min-w-0 рядом с truncate', () => {
  // Классическая ловушка flex: `truncate` на дочернем элементе не работает, пока у
  // его контейнера не снят минимальный размер по содержимому. Без `min-w-0` элемент
  // не сжимается, а РАСПИРАЕТ строку — ФИО «Константинопольский» уводит вбок шапку
  // целиком. Ловим только связку flex+truncate, где это правило обязательно.
  const offenders = []
  for (const f of FILES) {
    const lines = f.text.split('\n')
    lines.forEach((line, i) => {
      if (!/\btruncate\b/.test(line)) return
      // Явная ширина (`w-24`, `w-32`) снимает вопрос: элемент и так не шире заданного,
      // минимальный размер по содержимому на него не влияет. Пропускаем — иначе сторож
      // ругался бы на совершенно исправную строку с фиксированной колонкой.
      if (/\bw-(?:\d+|\[[^\]]+\])\b/.test(line)) return
      // Смотрим на родителя в пределах трёх строк выше — дальше связь уже не очевидна.
      const ctx = lines.slice(Math.max(0, i - 3), i).join(' ')
      if (!/\bflex\b/.test(ctx)) return
      if (!/min-w-0/.test(ctx) && !/min-w-0/.test(line)) {
        offenders.push(`${f.rel}:${i + 1}`)
      }
    })
  }
  // Список известных мест, где связка допустима (родитель — grid, а не flex-строка,
  // либо ширина задана явно). Пустой: на момент написания нарушений нет.
  assert.deepEqual(offenders.slice(0, 12), [],
    'truncate внутри flex без min-w-0 у родителя — текст распирает строку вместо обрезки')
})
