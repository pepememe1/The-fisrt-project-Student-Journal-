"""Что из оценок видит СТУДЕНТ и когда. Три фазы учебного года.

━━ ПОВОД ━━
Живая жалоба Влада (06.09.2026): «в июле у нас был прогон по предметам и я за один
предмет поставил оценку, сейчас автоматически спарсилась программа обучения 3-го курса
где этот предмет есть, а оценку всё ещё видно».

Требование дословно:
  • сентябрь → зимние каникулы: оценки видны, но ТОЛЬКО по предметам, оставшимся в
    программе нового семестра;
  • доходит до лета → оценки «останавливаются», видны только ИТОГОВЫЕ (дата кастомная,
    её выставляет администратор — «когда по сути зачёты и экзамены уже сданы»);
  • 1 сентября → оценки уходят в АРХИВ: администратор смотрит программу за семестры с
    оценками, студент своих старых оценок не видит.

━━ ЗАЧЕМ ЭТО ВООБЩЕ ━━
Причина названа самим Владом и она арифметическая: «если в прошлом семестре студент был
двоечник, а сейчас отличник, чтобы он не был в среднем троечником, т.к. семестры разные».
Средний балл, смешавший два семестра, не описывает НИ ОДИН из них — и хуже того, он
выглядит как настоящий средний, потому что цифра честная.

━━ ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ ━━
Правило читают студент, родитель, Вектор, ЗЕТ, долги, статистика и ачивки. Разложить
условие по ним значило бы восемь мест, где однажды забудут, — а первое забытое здесь это
чужой семестр в среднем балле, то есть ровно то, от чего правило и заведено. Здесь оно
одной чистой функцией и проверяется числами (`server/tests/test_grade_policy.py`).

⚠️ ПРАВИЛО КАСАЕТСЯ ТОЛЬКО СТУДЕНТА И РОДИТЕЛЯ. Преподаватель ведёт журнал, куратор
разбирает долги, администратор смотрит архив по семестрам — им нужна полная картина, и
прятать её значило бы сделать продукт неработающим ради красивого среднего у студента.

⚠️ НИ ОДНА ОЦЕНКА НЕ УДАЛЯЕТСЯ. «Обнуляются» здесь означает «перестают показываться
студенту как текущие»: строки лежат в базе, их видят администратор и выгрузки. Удалять
историю успеваемости нельзя — это документ.
"""
from __future__ import annotations

#Фаза «идёт учёба»: видны текущие оценки по предметам действующей программы.
PHASE_LIVE = "live"
#Фаза «сессия сдана»: поурочные оценки скрыты, видны только ИТОГОВЫЕ.
PHASE_FROZEN = "frozen"


def parse_freeze(value) -> tuple | None:
    """«ДД.ММ» → (день, месяц) или None, если не задано/не разобрать.

    ⚠️ Год НЕ хранится намеренно: дата повторяется каждый учебный год, и записанный год
    пришлось бы править вручную каждый июнь — ровно тот класс, из-за которого курс
    группы хранится годом поступления, а не числом курса.

    ⚠️ Не разобрали — это «не задано», а не «сегодня». Непонятная строка не имеет права
    молча скрыть студенту оценки: отсутствие даты оставляет прежнее поведение.
    """
    if not value:
        return None
    parts = str(value).strip().split(".")
    if len(parts) < 2:
        return None
    try:
        day, month = int(parts[0]), int(parts[1])
    except (TypeError, ValueError):
        return None
    if not (1 <= day <= 31 and 1 <= month <= 12):
        return None
    return day, month


def phase(today, term_semester, freeze_value) -> str:
    """Какая сейчас фаза для показа оценок студенту.

    :param today: дата (`date`/`datetime`) — «сегодня» вызывающего
    :param term_semester: семестр текущего термина (1 — осень, 2 — весна)
    :param freeze_value: «ДД.ММ» из настроек администратора или пусто

    Правила:
      • дата заморозки не задана → всегда `live`. Отсутствующая настройка обязана
        оставлять прежнее поведение: скрыть оценки «по умолчанию» значило бы отнять их у
        всего колледжа у того, кто просто обновился;
      • заморозка действует ТОЛЬКО в ВЕСЕННЕМ семестре. Осенью «зачёты и экзамены сданы»
        означает зимнюю сессию, после которой начинается новый семестр, а не конец года;
        применить её осенью значило бы заморозить журнал на зимних каникулах, когда
        занятия ещё будут (прямая просьба: «сентябрь → зимние каникулы оценки видны»);
      • наступила дата заморозки и позже → `frozen` до 31 августа. С 1 сентября термин
        меняется сам (`db.default_term`), и прошлые оценки уходят из выборки по периоду —
        отдельного правила для «архива» здесь не нужно.
    """
    fz = parse_freeze(freeze_value)
    if fz is None or int(term_semester or 0) != 2:
        return PHASE_LIVE
    day, month = fz
    #Сравниваем ПАРАМИ (месяц, день) — год у даты заморозки не хранится, и подставлять
    #его пришлось бы гаданием на границе января.
    return PHASE_FROZEN if (today.month, today.day) >= (month, day) else PHASE_LIVE


def hide_lesson_grades(current_phase: str) -> bool:
    """Прятать ли поурочные оценки. Итоговые не прячутся НИКОГДА.

    Итоговая — это то, что уходит в зачётку; скрыв её, мы оставили бы студента без
    единственного числа, которое после сессии вообще имеет смысл.
    """
    return current_phase == PHASE_FROZEN


def visible_records(records: dict, current_phase: str) -> dict:
    """Оценки, которые студенту показывать МОЖНО, по фазе.

    В фазе `frozen` возвращается пустая карта: поурочных оценок студент не видит, а
    итоговые живут в отдельной таблице (`TermGrade`) и через эту функцию не проходят.

    ⚠️ Возвращаем ПУСТУЮ КАРТУ, а не `None`: вызывающие складывают средний, считают долги
    и рисуют таблицу, и `None` означал бы для них падение вместо «оценок нет».
    """
    return {} if hide_lesson_grades(current_phase) else dict(records or {})
