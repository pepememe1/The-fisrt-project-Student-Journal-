"""Перевод учебной группы на новый курс: старое — в архив, преподаватели откреплены.

━━ ПОВОД ━━
Живая жалоба Влада (05.09.2026): «ещё в июле была старая программа обучения за второй
курс, первого сентября программа сменилась, но некоторые предметы остались те же — в
итоге сейчас видно старые оценки». Полный разбор — `docs/PLAN-COURSE-ROLLOVER.md`.

━━ ПОЧЕМУ СИМПТОМ ОДИН, А ПРИЧИН ТРИ ━━
🔥 **Занятие БЕЗ штампа термина считалось ТЕКУЩИМ.** `webdata.current_term_lessons`
пропускает строку с пустым `year` — компромисс был назван честно («отличить нечем»), но
на нём стоят витрина студента, статистика, ЗЕТ, долги, пропуски, риск отчисления и
ответы Вектора. Предмет, оставшийся в новой программе под ТЕМ ЖЕ именем, проходит и
второй фильтр (`current_subject_lessons` сверяет ИМЯ) — и оценки прошлого курса
доезжают до экрана без единого препятствия.

⚠️ При этом ЖУРНАЛ берёт занятия через `group_lessons(year=…, semester=…)`, а тот
занятие без штампа не находит вовсе. То есть «Главная» и «Журнал» у одного и того же
студента отвечали на «какие у меня оценки» ПО-РАЗНОМУ — наш обычный класс «две правды
на соседних экранах», и по экрану не понять, какой из них верить.

⚠️ **Отличить прошлое от текущего ЕСТЬ ЧЕМ: у занятия есть ДАТА.** Именно она решает,
какому периоду занятие принадлежит, — тем же календарём, что `db.default_term()`.

🔥 **Преподаватель не откреплялся, потому что мост назначений не знает про термин.**
`webdata._assignments_fallback` собирает пары (группа, предмет) из `Lesson` БЕЗ фильтра
по периоду, поэтому преподаватель без строк `SubjectHours` на новый термин продолжает
видеть прошлогодние группы как действующие. Это и есть «сейчас этого не происходит».

🔥 **Гашение предметов не срабатывает на предмет, который ОСТАЛСЯ.**
`write._archive_dropped_subjects` трогает только ВЫПАВШИЕ из плана предметы, а
«Математика» на 2 и на 3 курсе — одно и то же имя. Ни строка часов, ни назначенный
преподаватель, ни старые занятия не задевались вовсе.

━━ ЧТО ИМЕННО ПИШЕТ ПЕРЕВОД ━━
⚠️ **Не удаляет и не переписывает НИ ОДНОЙ оценки.** Своего периода у оценки нет — он
производный от занятия; здесь занятию проставляется период, к которому оно и
относилось. Архив у нас всегда означал «видно тем, кто смотрит прошлое», а не «стёрто».

⚠️ **Но полей он трогает БОЛЬШЕ, чем два** (уточнено 06.09.2026 по возражению Полковника:
формулировка «трогает только `Lesson` и `SubjectHours`» была неправдой). Полный список:
`Lesson.year/semester/updated_at`, `SubjectHours.teacher_id/teacher_id_2/updated_at`,
`Group.assignments_reset_term/updated_at` и — через `group_archive.witness` —
`Group.last_course/last_course_year`. Последнее не косметика: по свидетельству курса
`group_archive.candidates` и `course_rollover.pending` вынесут вердикт в СЛЕДУЮЩЕМ
сентябре, и умолчать о нём значило бы спрятать причину будущего решения.

⚠️ Не решает, сколько курсов в специальности: такого справочника нет, и выдумывать
«последний курс» числом было бы гаданием. Признак выпуска — отсутствие в расписании
(см. `group_archive.candidates`).

⚠️ **ПЕРЕВОД ТЕПЕРЬ АВТОМАТИЧЕСКИЙ (06.09.2026, решение Влада: «кнопку ручного перевода
на курс нужно убрать, всё делается автоматически»).** Здесь стояло обратное — «перевод
запускает администратор», — и довод был не пустой: группа пропадает из расписания и при
сбое портала, а автомат унёс бы полколледжа молча.

🔒 **Автомат безопасен ровно потому, что НЕ СПРАШИВАЕТ ПОРТАЛ.** Он смотрит на календарь
и на собственные данные группы:
  • новый УЧЕБНЫЙ ГОД наступает 1 сентября по `db.default_term()` — это факт календаря, а
    не мнение внешнего сайта, и в день, когда портал лежит, он такой же верный;
  • период занятия вычисляется из его СОБСТВЕННОЙ даты, а не из догадки о курсе.
⚠️ Утверждение проверяется СЧЁТЧИКОМ вызовов, а не подменой-исключением: `portal_course`
глотает любую ошибку своим `try`, и сторож, роняющий обращение к расписанию, оставался бы
зелёным рядом с настоящим походом в портал (так и было до 06.09.2026).
Именно портальный признак («курса нет в расписании») остался ручным — он и был опасен, и
им по-прежнему ведает администратор через архив групп (`group_archive.candidates`).

⚠️ Автомат ИДЕМПОТЕНТЕН и срабатывает не чаще раза в учебный год на группу: метку
`assignments_reset_term` он же и ставит. Без этого открепление преподавателей повторялось
бы каждый запуск сервера, то есть админ не смог бы назначить их вовсе.
"""
from __future__ import annotations

from datetime import datetime, timezone

from .models import Group, Lesson, SubjectHours


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def term_label(year: str, semester) -> str:
    """«2026/2027·1» — как период выглядит в метке `Group.assignments_reset_term`."""
    return f"{year}·{int(semester or 0)}"


def previous_term(year: str, semester) -> tuple:
    """Период, ПРЕДШЕСТВУЮЩИЙ указанному: весна → своя осень, осень → прошлая весна.

    ⚠️ Год у нас строкой «2025/2026», а не числом, поэтому шаг назад из осени — это
    разбор обеих половин. Неразбираемую строку возвращаем как есть с семестром 2: молча
    подставить «какой-нибудь» год значило бы отправить занятия в выдуманный период.
    """
    sem = int(semester or 0)
    if sem == 2:
        return year, 1
    try:
        a, b = (year or "").split("/")
        return f"{int(a) - 1}/{int(b) - 1}", 2
    except (ValueError, AttributeError):
        return year, 2


def term_of_lesson(lesson, fallback: tuple) -> tuple:
    """Какому периоду принадлежит занятие: по его ДАТЕ, иначе — `fallback`.

    Дата приходит в формате «ДД.ММ.ГГГГ» (тот же разбор, что у отчёта куратора). Дата
    пустая или битая — берём период, из которого группа уходит: это заведомо не
    «сегодняшний», а значит занятие перестаёт подмешиваться к текущим оценкам. Точнее
    гадать не на чем, и притворяться, что мы знаем, нельзя.
    """
    from . import db as _db
    from .curator_report import parse_ddmmyyyy
    #⚠️ `parse_ddmmyyyy` отдаёт КОРТЕЖ (год, месяц, день), а не дату — он заведён для
    #сравнения, а не для арифметики. Собираем дату здесь и ловим невозможные числа
    #(«31.02.2026» руками вбить можно): битая дата — это «не знаем», а не «сегодня».
    parts = parse_ddmmyyyy(getattr(lesson, "date", "") or "")
    if parts is None:
        return fallback
    try:
        when = datetime(parts[0], parts[1], parts[2], tzinfo=timezone.utc)
    except (ValueError, TypeError):
        return fallback
    return _db.term_for_date(when)


def stamp_untermed_lessons(db, group: str, fallback: tuple, now: str = "") -> int:
    """Проставить период занятиям группы, у которых его нет. Возвращает число строк.

    ⚠️ `updated_at` БАМПАЕТСЯ намеренно, и цена названа честно: каждый десктоп перекачает
    эти занятия следующим pull-ом. Без бампа офлайн-копия продолжила бы считать их
    текущими — то есть показывать прошлогодние оценки как сегодняшние ровно там, где
    преподаватель работает без сети. Это и есть дефект, ради которого правка делается;
    экономить здесь трафик значило бы починить только половину продукта.
    (Ср. запрет бампа при простановке `student_id`: там поле было ТЕХНИЧЕСКОЕ и на показ
    не влияло, здесь меняется то, в каком семестре занятие показывается.)
    """
    now = now or _now_iso()
    rows = (db.query(Lesson)
            .filter(Lesson.group_name == group, Lesson.deleted == False,  # noqa: E712
                    (Lesson.year == "") | (Lesson.year.is_(None))).all())
    for row in rows:
        year, sem = term_of_lesson(row, fallback)
        row.year = year
        row.semester = int(sem)
        row.updated_at = now
    return len(rows)


def restamp_future_dated_lessons(db, group: str, now: str = "") -> int:
    """Занятие не может принадлежать периоду, который начался ПОЗЖЕ его собственной даты.

    🔥 ЭТО И БЫЛА ПРИЧИНА ЖАЛОБЫ (найдено на боевых данных 07.09.2026). Разбор:
    занятия с датами 17.07.2026, 23.07.2026 и 12.08.2026 лежали на бою со штампом
    `2026/2027·1` — то есть НОВОГО учебного года, который начинается 1 сентября. Поэтому
    июльские оценки честно проходили любой фильтр по периоду и показывались как текущие:
    формально они и были «текущими».

    ⚠️ Откуда взялся неверный штамп. Граница лета в `db.default_term` двигалась ТРИЖДЫ:
    1 июля → 25 августа → 1 сентября (история — в её докстринге). Занятия, заведённые под
    ранней границей, получили новый учебный год ещё в июле — и остались с ним навсегда:
    правку границы применили к БУДУЩИМ штампам, а уже проставленные никто не пересчитал.
    Это наш класс «исправили правило, забыли данные».

    ⚠️ Прошлая починка (`stamp_untermed_lessons`) здесь не срабатывала вовсе: она чинит
    занятия с ПУСТЫМ периодом, а у этих он заполнен — просто неверно. Ровно поэтому
    автоперевод на бою отчитался «занятий в архив 0» при живой жалобе.

    🔒 ПОЧЕМУ ПРАВИМ ТОЛЬКО «ПЕРИОД ПОЗЖЕ ДАТЫ», А НЕ ЛЮБОЕ РАСХОЖДЕНИЕ. Обратный случай
    законен: пересдача в сентябре относится к весенней сессии, и её занятие честно
    датировано позже своего периода. Слепое выравнивание «по дате» унесло бы такие
    пересдачи в новый семестр. А вот период, начавшийся ПОСЛЕ занятия, невозможен по
    смыслу: занятие не может принадлежать году, который ещё не наступил.

    ⚠️ Занятия без разбираемой даты НЕ ТРОГАЕМ: сверять нечего, а гадать нельзя.
    """
    from . import webdata as W
    now = now or _now_iso()
    rows = (db.query(Lesson)
            .filter(Lesson.group_name == group, Lesson.deleted == False,  # noqa: E712
                    Lesson.year != "").all())
    fixed = 0
    for row in rows:
        by_date = term_of_lesson(row, ())
        if not by_date:                       #даты нет или не разобрали — не наше дело
            continue
        stored = (row.year, int(row.semester or 0))
        if W._term_key(stored) <= W._term_key(by_date):
            continue                          #период не позже даты — законно, не трогаем
        row.year, row.semester = by_date[0], int(by_date[1])
        row.updated_at = now
        fixed += 1
    return fixed


def detach_teachers(db, group: str, year: str, semester, now: str = "") -> int:
    """Снять преподавателей со ВСЕХ строк часов группы за УКАЗАННЫЙ период.

    Прямое требование: «если сменился курс — все преподы от предметов открепляются».
    Снимаем ОБОИХ (`teacher_id` и `teacher_id_2`): предмет, вернувшийся в план через
    полгода, уже однажды оживал со вторым преподавателем, которого никто не назначал
    (см. `write._archive_dropped_subjects`).

    ⚠️ Трогаем только УКАЗАННЫЙ (новый) период. Строки прошлых семестров — история: по
    ним видно, кто вёл предмет тогда, и стирать это значило бы переписывать прошлое
    задним числом. Именно их читает карточка архивной группы (`group_archive.detail`).
    """
    now = now or _now_iso()
    rows = (db.query(SubjectHours)
            .filter(SubjectHours.group_name == group,
                    SubjectHours.year == year,
                    SubjectHours.semester == int(semester or 0)).all())
    touched = 0
    for row in rows:
        if not (row.teacher_id or getattr(row, "teacher_id_2", "")):
            continue
        row.teacher_id = ""
        row.teacher_id_2 = ""
        row.updated_at = now
        touched += 1
    return touched


def advance(db, group: str, now: str = "") -> dict | None:
    """Перевести группу на новый курс. None — такой группы нет.

    Три действия, каждое отвечает своему предложению жалобы:
      1. занятия без периода получают тот, в котором реально были (старые оценки — в
         архив, включая предметы, оставшиеся в новой программе);
      2. преподаватели откреплены от предметов НОВОГО периода;
      3. у группы ставится метка `assignments_reset_term` — с этого периода назначения
         обязаны быть ЯВНЫМИ, и мост `_assignments_fallback` к ней больше не применяется.

    ⚠️ Возвращаем, ЧТО ИМЕННО изменилось, а не голое «ok». Администратор нажимает эту
    кнопку раз в год и обязан видеть последствия: молчаливый успех неотличим от
    молчаливого промаха по имени группы.
    """
    from . import webdata as W
    row = db.get(Group, f"grp:{group}")
    if row is None or row.deleted:
        return None
    now = now or _now_iso()
    cur_y, cur_s = W.current_term(W.load_config(db))
    prev = previous_term(cur_y, cur_s)

    stamped = stamp_untermed_lessons(db, group, prev, now)
    restamped = restamp_future_dated_lessons(db, group, now)
    detached = detach_teachers(db, group, cur_y, cur_s, now)
    row.assignments_reset_term = term_label(cur_y, cur_s)
    row.updated_at = now
    #🔥 СВИДЕТЕЛЬСТВО КУРСА ЗДЕСЬ БОЛЬШЕ НЕ СТАВИТСЯ (06.09.2026, нашёл Полковник).
    #Тут стоял `GA.witness(db, row, W.group_course(db, group))` — и это был ЕДИНСТВЕННЫЙ
    #поход перевода в портал, ровно тот, которого он обязан избегать. Хуже того, на СТАРТЕ
    #сервера кэш индекса расписания пуст всегда, поэтому портал отвечал «не знаю»:
    #• у группы БЕЗ года поступления курс выходил None, и `witness` молча не писал ничего
    #  — то есть свидетельство, ради которого строка и стояла, не появлялось;
    #• у группы С годом записывался ФОРМУЛЬНЫЙ курс — то самое число, ради недоверия к
    #  которому `group_course` и ставит портал первым (болезнь ловилась трижды).
    #Свидетельство ведут те, у кого есть настоящий курс: кнопка «Запомнить текущие курсы»
    #и перевод периода. Перевод на курс — про ПЕРИОД занятий и назначения, и чужой
    #источник правды ему не нужен.
    return {
        "group": group,
        "term": {"year": cur_y, "semester": cur_s},
        "archived_term": {"year": prev[0], "semester": prev[1]},
        "lessons_stamped": stamped,
        "lessons_restamped": restamped,
        "teachers_detached": detached,
    }


def _mark_year(row) -> str:
    """Учебный год из метки `assignments_reset_term` («2026/2027·1» → «2026/2027»)."""
    mark = (getattr(row, "assignments_reset_term", "") or "")
    return mark.split("·")[0] if mark else ""


def needs_advance(db, row, cur_year: str) -> bool:
    """Нужен ли группе перевод ПРЯМО СЕЙЧАС. Ничего не меняет.

    Два условия, и оба обязательны:
      1. **учебный год сменился** относительно того, в котором группу переводили в
         последний раз (метка пуста — не переводили никогда);
      2. **у группы есть ПРОШЛОЕ** — занятие без периода или занятие более раннего
         периода.

    ⚠️ Второе условие — не перестраховка, а защита от разрушения. Группа, заведённая
    сегодня, метки не имеет, и без него автомат «перевёл» бы её на первом же запуске
    сервера, открепив преподавателей, которых администратор только что назначил.
    «Нет прошлого» значит «переводить не с чего», а не «переводить пора».
    """
    if _mark_year(row) == cur_year:
        return False
    has_untermed = (db.query(Lesson)
                    .filter(Lesson.group_name == row.name, Lesson.deleted == False,  # noqa: E712
                            (Lesson.year == "") | (Lesson.year.is_(None))).first() is not None)
    if has_untermed:
        return True
    return (db.query(Lesson)
            .filter(Lesson.group_name == row.name, Lesson.deleted == False,  # noqa: E712
                    Lesson.year != "", Lesson.year < cur_year).first() is not None)


def autorun(db) -> list[dict]:
    """Перевести на новый курс все группы, которым это нужно. Зовётся при старте сервера.

    Возвращает список того, что сделано, — по одной записи на переведённую группу. Пусто
    значит «переводить было нечего», и это нормальный, самый частый исход.

    ⚠️ Пишем в ОБЫЧНЫЙ лог, а не в журнал аудита: аудит — след действий ЧЕЛОВЕКА, а здесь
    действие календаря. Но молчать нельзя: перевод откреплял преподавателей, и админ,
    обнаруживший пустые назначения, должен иметь возможность узнать, когда и почему.

    ⚠️ Отказ на одной группе не должен останавливать остальные и тем более ронять запуск
    сервера. Перевод идемпотентен, поэтому непереведённая группа просто дождётся
    следующего старта — это лучше, чем сервер, который не поднимается из-за одной строки.
    """
    import logging
    from . import webdata as W
    cur_year, _cur_sem = W.current_term(W.load_config(db))
    done: list[dict] = []
    rows = (db.query(Group)
            .filter(Group.deleted == False, Group.archived == False)  # noqa: E712
            .order_by(Group.name).all())
    repaired = 0
    for row in rows:
        try:
            #🔥 ПОЧИНКА ШТАМПОВ — ДЛЯ ВСЕХ ГРУПП, а не только для переводимых. Занятие с
            #периодом ПОЗЖЕ собственной даты показывается как текущее в любой группе, и
            #ждать, пока она соберётся «переходить на курс», означало бы оставить жалобу
            #в силе там, где перевод не нужен. Правка идемпотентна: второй раз чинить
            #нечего.
            repaired += restamp_future_dated_lessons(db, row.name)
            if not needs_advance(db, row, cur_year):
                continue
            out = advance(db, row.name)
            if out:
                done.append(out)
        except Exception as e:                                     # noqa: BLE001
            logging.getLogger("gradebook.course_rollover").warning(
                "[курс] группу %s перевести не удалось: %s", row.name, e)
    if done or repaired:
        db.commit()
        logging.getLogger("gradebook.course_rollover").warning(
            "[курс] учебный год %s: переведено групп %d, занятий в архив %d, "
            "откреплено преподавателей %d, исправлено штампов периода %d",
            cur_year, len(done),
            sum(d["lessons_stamped"] for d in done),
            sum(d["teachers_detached"] for d in done), repaired)
    return done


def assignments_must_be_explicit(db, group: str, year: str, semester) -> bool:
    """Выключен ли мост назначений у ЭТОЙ группы на ЭТОТ период.

    True — группу переводили на новый курс, и «нет строки с моим id» означает «мне тут
    не назначено», а не «данные ещё не ввели».

    ⚠️ Сравнение НЕ «равно», а «период не старше метки»: метка ставится один раз, а
    семестры идут дальше, и после весны мост не имеет права ожить сам собой.
    """
    from . import webdata as W
    row = db.query(Group).filter(Group.name == group).first()
    mark = (getattr(row, "assignments_reset_term", "") or "") if row is not None else ""
    if not mark:
        return False
    try:
        mark_year, mark_sem = mark.split("·")
        return W._term_key((year, int(semester or 0))) >= W._term_key((mark_year, int(mark_sem)))
    except (ValueError, AttributeError):
        return False
