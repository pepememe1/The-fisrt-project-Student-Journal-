#проверяет его так же, как у всех. Иначе получилась бы ручка «выдай мне ачивку», которой
#в продукте нет и быть не должно (§ачивок).
#
#⚠️ Границы названы: доля 90 %, а не 100 — при 100 % пропал бы сам факт «выпало», и
#проверить, что бросок вообще работает, стало бы нечем.
LUCKY_PERCENT = 90.0


def _lucky_logins() -> set:
    """Логины, которым пасхалки выпадают почти всегда. Пусто — режим выключен."""
    import os
    raw = os.environ.get("GRADEBOOK_LUCKY_LOGINS", "")
    return {x.strip().lower() for x in raw.split(",") if x.strip()}


def is_lucky(login: str) -> bool:
    """Входит ли человек в список проверяющих."""
    return bool(login) and login.strip().lower() in _lucky_logins()


def _hit(egg_id: str, lucky: bool = False) -> bool:
    """Сам бросок: выпало или нет. Без базы, без побочных эффектов.

    ⚠️ Вынесено отдельной функцией не ради красоты, а чтобы её можно было ПРОВЕРИТЬ.
    Раньше формула жила внутри `roll`, и тест повторял её у себя — то есть сверял копию
    с копией и остался бы зелёным, даже если бы в продукте её изменили. Теперь тест
    гоняет ровно тот код, который работает на бою.

    Две формы записи шанса, и обе нужны (см. EGG_CHANCES и EGG_PERCENT):
      • знаменатель — «один раз из N», для редких находок;
      • доля в процентах — для тех, где важна именно частота показа. Берётся
        `random.random()`, а не `randint`: целочисленный бросок не умеет 7.7 % и молча
        округлил бы её до 7 или 8.
    """
    #Проверяющий: шанс подменяется ОДНОЙ величиной на все пасхалки — так проверка не
    #зависит от того, какая из них редкая, а какая частая.
    if lucky:
        return random.random() * 100 < LUCKY_PERCENT
    percent = EGG_PERCENT.get(egg_id)
    if percent:
        return random.random() * 100 < percent
    chance = EGG_CHANCES.get(egg_id)
    return bool(chance) and random.randint(1, chance) == 1


def roll(egg_id: str, user_id: str, db: Session) -> bool:
    """Бросок для одной пасхалки. True — показываем.

    Неизвестный `egg_id` — всегда False: молча ничего не показываем, но пишем в лог.
    Тихо возвращать False без следа нельзя, иначе опечатка в имени превратится в
    «пасхалка не работает» без единой подсказки почему."""
    chance = EGG_CHANCES.get(egg_id)
    percent = EGG_PERCENT.get(egg_id)
    if not chance and not percent:
        _log.warning("бросок для неизвестной пасхалки: %s", egg_id)
        return False
    if not user_id:
        return False

    #Кулдаун проверяем ДО броска: иначе шанс тратился бы вхолостую, а на боевой машине
    #это ещё и лишняя запись в базу на каждой смене вкладки.
    cooldown = EGG_COOLDOWN_S.get(egg_id)
    if cooldown and was_triggered_recently(user_id, egg_id, db, within_s=cooldown):
        return False

    #Логин достаём из `user_id` (`stud:ivanov` / `teach:petrov` / голый логин админа):
    #списка проверяющих в базе нет, и заводить его ради временной проверки незачем.
    if not _hit(egg_id, lucky=is_lucky(user_id.split(":")[-1])):
        return False

    db.add(EasterEggLog(user_id=user_id, egg_id=egg_id, triggered_at=_now_iso(),
                        created_ts=int(datetime.now(timezone.utc).timestamp())))
    db.commit()
    return True


def mark_triggered(egg_id: str, user_id: str, db: Session) -> bool:
    """Записать след срабатывания БЕЗ броска — для пасхалок без шанса.

    ⚠️ Нужна ровно там, где условие детерминированное (ULTRAKILL показывается каждому
    отличнику, а не раз в N заходов). Без следа `claim` откажет в ачивке, потому что
    честность ачивок держится именно на нём.

    ⚠️ Звать ТОЛЬКО после проверки условия НА СЕРВЕРЕ. Открытой ручки у этой функции
    нет и быть не должно: `mark_triggered` без условия — это и есть «выдай мне ачивку»,
    от которой защищает вся остальная конструкция."""
    if egg_id not in ACHIEVEMENTS.values():
        _log.warning("след для неизвестной пасхалки: %s", egg_id)
        return False
    if not user_id:
        return False
    db.add(EasterEggLog(user_id=user_id, egg_id=egg_id, triggered_at=_now_iso(),
                        created_ts=int(datetime.now(timezone.utc).timestamp())))
    db.commit()
    return True


