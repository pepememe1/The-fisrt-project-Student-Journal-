#━━ «МИНА» В ЗАГОЛОВКАХ ОТВЕТА-ПРИМАНКИ (Moving Target) ━━
#Идея Ярослава (fsociety, 06.09.2026): ответ приманки выглядит как забытый в проде
#отладчик, «случайно» отдающий в HTTP-заголовке хеш служебной учётки в НАШЕЙ реальной
#схеме (`hybrid_sha512_gost512`, см. `security.py`). Сканер видит знакомый формат,
#скармливает его Hashcat — и жжёт GPU впустую.
#
#🔑 ДВА ПРИНЦИПА, БЕЗ КОТОРЫХ ЭТО НЕ МИНА, А ДЫРА:
#  • CPU у НАС = 0. Мы НИЧЕГО не считаем. `fake` — декоративные случайные байты, а не
#    результат KDF. Это не экономия, это и есть смысл: под случайные 64 байта нет ни
#    одного прообраза, поэтому «Бесконечный Стрибог» бесконечен буквально — атакующий не
#    остановится НИКОГДА, находить нечего. Настоящий хеш (200 000 итераций НА ЗАПРОС)
#    стоил бы нам ядра И дал бы ответ, на котором перебор заканчивается.
#  • НИ ОДНОГО настоящего секрета. `salt`/`fake` — `os.urandom`, не производные от
#    `JWT_SECRET` и не наш хеш. Утечь тут нечему: заголовок несёт мусор правдоподобной
#    формы, а не наши данные. Поэтому этот модуль НЕ импортирует `security` и не
#    обращается к `JWT_SECRET` — держит сторож в тестах.
#
#Moving Target: на ПОВТОРНЫХ касаниях с одного источника число итераций РАСТЁТ, а соль
#меняется каждый ответ. Для Hashcat это каждый раз новая задача — накопленный прогресс
#обнуляется. Счётчик источника живёт в памяти процесса (как бан и дедуп) и переживать
#рестарт не обязан: после перезапуска мина просто начинается заново.
MINE_HEADER = "X-Debug-Auth"
_MINE_BASE_ITERS = 200_000       #наша реальная стоимость SHA-ступени — для правдоподобия
_MINE_STEP_ITERS = 150_000       #на сколько «поднимаем защиту» с каждым повторным касанием
_MINE_MAX_ITERS = 5_000_000      #потолок: дальше числа перестают быть правдоподобными
_MINE_GOST_ITERS = 2000          #ГОСТ-ступень как на бою (см. security._gost_iters)
_mine_hits: dict = {}
_MINE_TTL_S = 300


def _mine_iters(ip: str, now: float) -> int:
    """Сколько «итераций» показать источнику. Растёт с каждым касанием (Moving Target),
    не считая ничего, — арифметика по счётчику в памяти. Окно то же, что у дедупликации:
    после паузы источник «остывает» и мина для него снова начинается с базового числа."""
    key = (ip or "").strip()
    last, count = _mine_hits.get(key, (0.0, 0))
    count = 0 if (now - last >= _MINE_TTL_S) else count
    count += 1
    _mine_hits[key] = (now, count)
    #Подметаем на месте: без этого словарь растёт на каждый новый адрес и живёт вечно.
    if len(_mine_hits) > 4096:
        for k, (ts, _c) in list(_mine_hits.items()):
            if now - ts >= _MINE_TTL_S:
                _mine_hits.pop(k, None)
    return min(_MINE_BASE_ITERS + _MINE_STEP_ITERS * (count - 1), _MINE_MAX_ITERS)


def mine_headers(ip: str, now: float = 0.0) -> dict:
    """Заголовки-приманка для ответа на `is_canary`-путь. НИЧЕГО не хеширует.

    Значение имитирует наш формат `hybrid_sha512_gost512$<sha>-<gost>$<salt>$<hash>`.
    `salt`/`fake` — случайные (см. запрет на настоящие секреты в шапке секции), поэтому
    меняются на каждый ответ; число итераций растёт по источнику."""
    import os
    import time as _t
    now = now or _t.time()
    iters = _mine_iters(ip, now)
