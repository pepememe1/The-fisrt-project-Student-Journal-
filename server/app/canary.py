#━━ ДЕДУПЛИКАЦИЯ ЗАПИСЕЙ ━━
#🔥 НАЙДЕНО ПОЛКОВНИКОМ 05.09.2026. Раньше запись делалась «если бан удался»
#(`if throttle.ban_ip(...)`), и это было неверно ДВАЖДЫ:
#  • **доверенный адрес не банится — и не записывался ВООБЩЕ.** А в белом списке у нас
#    сеть колледжа (один NAT). То есть студент с ноутбука в аудитории проходил
#    `/.env`, `/wp-login.php`, `/.git/config` — и детектор молчал. Приманка была слепа
#    ровно к инсайдеру, то есть к самому вероятному нарушителю;
#  • комментарий обещал «только при первом бане», но `ban_ip` возвращает True на
#    КАЖДОМ вызове для недоверенного адреса. Дедупликацию на деле давал ранний 429
#    выше по потоку, а два одновременных запроса до первого бана дали бы две записи.
#
#Теперь решения РАЗВЕДЕНЫ, и это принципиально: **банить и замечать — разные вещи.**
#Бан щадит доверенных (иначе один сканер отрежет здание), запись — не щадит никого,
#потому что она и есть смысл приманки.
_seen: dict = {}
#Пять минут: сканер шлёт сотни запросов подряд, и строка на каждый превратила бы журнал
#безопасности в лог доступа, где нужную запись уже не найти. А через пять минут это
#либо новая попытка, либо продолжение — и то и другое стоит отдельной строки.
_SEEN_TTL_S = 300


def should_record(ip: str, now: float = 0.0) -> bool:
    """Записывать ли это срабатывание. Дедупликация по источнику, а не по бану.

    ⚠️ Хранится в памяти процесса, как и сам бан. Рестарт сбрасывает — и это честно:
    после перезапуска первое же обращение снова попадёт в журнал."""
    import time as _t
    now = now or _t.time()
    key = (ip or "").strip()
    last = _seen.get(key, 0.0)
    if now - last < _SEEN_TTL_S:
        return False
    _seen[key] = now
    #Подметаем на месте: без этого словарь растёт на каждый новый адрес и живёт вечно.
    if len(_seen) > 4096:
        for k, ts in list(_seen.items()):
            if now - ts >= _SEEN_TTL_S:
                _seen.pop(k, None)
    return True


def reset_seen() -> None:
    """Сброс дедупликации — для тестов."""
    _seen.clear()


def ip_fingerprint(ip: str) -> str:
    """Короткий солёный отпечаток адреса для журнала. НЕ сам адрес.

    ⚠️ `hashlib`, а не встроенный `hash()`: последний солится случайно при КАЖДОМ старте
    процесса, и отпечатки одного адреса до и после рестарта не совпали бы — то есть
    ровно та связность, ради которой отпечаток и заводится, пропала бы. Эта грабля у нас
    уже была с постоянной меткой аватарки.

    ⚠️ Соль — секрет подписи сервера. Без соли отпечаток бесполезен как защита: адресов
    всего четыре миллиарда, и таблицу перебирают за минуты. С солью восстановить адрес
    может только тот, кто уже владеет секретом машины, — а это компрометация целиком, и
    журнал приманок там будет наименьшей из проблем.

    ⚠️ 16 шестнадцатеричных знаков, а не полные 64: столкновение здесь ничего не ломает
    (мы не принимаем по отпечатку решений), а короткая строка читается человеком.
    """
    import hashlib
    from .config import JWT_SECRET
    raw = "%s|%s" % (JWT_SECRET, (ip or "").strip())
    return "h:" + hashlib.sha256(raw.encode("utf-8")).hexdigest()[:16]


