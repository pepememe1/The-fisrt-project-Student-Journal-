"""
activity_state.py — состояние ИДУЩИХ активностей, в памяти процесса.

Зачем не в БД (docs/done/PLAN-ACTIVITIES.md §2). Ход синхронной активности меняется на каждое
действие каждого участника: тридцать одновременных ответов на вопрос соревнования — это
тридцать транзакций в SQLite с блокировкой записи ровно в тот момент, когда группа ждёт
таблицу на экране. В БД ложится ИТОГ (`ActivityResult`), а не каждый промежуточный кадр.

⚠️ ЭТО ЗАКРЕПЛЯЕТ НАС НА ОДНОМ ПРОЦЕССЕ uvicorn. Реестр веб-сокетов (`_WSManager` в
routers/messenger.py) уже живёт в памяти по той же причине, так что новое ограничение мы
не вводим — но и не снимаем. Второй воркер (`--workers 2`) сломает оба: половина
участников попадёт в процесс, который про активность не знает. Переход на несколько
процессов потребовал бы общего брокера (например Redis pub/sub) — отдельная работа, и
на машине ВСГУТУ она всё равно не нужна: там хватает одного процесса с запасом.

⚠️ Рестарт сервера теряет ход активности — это ОСОЗНАННО. Восстанавливать недоигранное
нечестно: за время рестарта вопрос уже потерял смысл (соревнование идёт на секунды), а
воскресшая на экране викторина, где часть ответов пропала, хуже честного «завершена».
Строки `Activity` в БД при этом остаются со статусом `running` — их закрывает
`sweep_stale()` при первом же обращении к беседе.
"""
import threading
import time

#Замок один на весь реестр, а не на активность. Операции здесь — это правка небольшого
#словаря (микросекунды), а замок на активность потребовал бы замка для защиты словаря
#замков. Обработчики REST ходят сюда из пула потоков, значит гонка реальна: без замка два
#одновременных ответа могли бы получить ОДИН И ТОТ ЖЕ `seq`, и клиент отбросил бы второй
#кадр как устаревший (см. правило про монотонный seq в PLAN-ACTIVITIES §7).
_LOCK = threading.RLock()
_STATES: dict[str, "_Live"] = {}

#Активность без единого обращения дольше этого срока считается брошенной (хост закрыл
#вкладку и не вернулся). Шесть часов — заведомо больше любой пары.
STALE_AFTER_S = 6 * 60 * 60


class _Live:
    """Живое состояние одной активности."""

    def __init__(self, activity_id: str, kind: str, payload: dict):
        self.activity_id = activity_id
        self.kind = kind
        self.payload = dict(payload or {})
        #Монотонный счётчик кадров. Клиент отбрасывает кадр с меньшим `seq`, пришедшим
        #позже: сеть переупорядочивает пакеты, и «свежий» кадр по значению поля отличить
        #нельзя — этот проект уже дважды ловил такие гонки (расписание, категории).
        self.seq = 0
        self.touched_at = time.monotonic()


def start(activity_id: str, kind: str, payload: dict = None) -> dict:
    """Завести состояние. Повторный вызов ПЕРЕЗАПИСЫВАЕТ — активность стартует один раз,
    и если строка тут осталась от прошлой с тем же id, она заведомо мусор."""
    with _LOCK:
        _STATES[activity_id] = _Live(activity_id, kind, payload or {})
        return _snapshot(_STATES[activity_id])


def get(activity_id: str) -> dict | None:
    """Снимок состояния или None, если активность не идёт (или пережила рестарт)."""
    with _LOCK:
        live = _STATES.get(activity_id)
        if live is None:
            return None
        live.touched_at = time.monotonic()
        return _snapshot(live)


def patch(activity_id: str, changes: dict) -> dict | None:
    """Изменить поля состояния и поднять `seq`. None — активности нет в памяти.

    Возвращает СНИМОК, а не сам объект: вызывающий отдаёт его в WS-рассылку, а отдавать
    наружу живой словарь под замком значит позволить читать его, пока другой поток пишет.
    """
    with _LOCK:
        live = _STATES.get(activity_id)
        if live is None:
            return None
        live.payload.update(changes or {})
        live.seq += 1
        live.touched_at = time.monotonic()
        return _snapshot(live)


def bump(activity_id: str) -> dict | None:
    """Поднять `seq` без изменения полей (кадр «состояние перечитай сам»)."""
    return patch(activity_id, {})


def drop(activity_id: str) -> None:
    with _LOCK:
        _STATES.pop(activity_id, None)


def stale_ids() -> list[str]:
    """id активностей, к которым давно не обращались, — и заодно снимает их с учёта.

    Нужен для того, чтобы `running`-строки в БД не копились после того, как хост просто
    закрыл вкладку: без уборки беседа получала бы вечный 409 «активность уже идёт» и
    запустить новую было бы нельзя вовсе."""
    now = time.monotonic()
    with _LOCK:
        dead = [k for k, v in _STATES.items() if now - v.touched_at > STALE_AFTER_S]
        for k in dead:
            _STATES.pop(k, None)
        return dead


def reset() -> None:
    """Полная очистка. ⚠️ Любой НОВЫЙ словарь состояния в этом модуле обязан попадать
    сюда: тесты пересоздают базу между собой, а память процесса переживает это — и
    активность из прошлого теста ловилась бы в следующем как «уже идёт». Ровно эта грабля
    уже стоила нам зависимых от порядка тестов в `throttle.reset()`."""
    with _LOCK:
        _STATES.clear()


def _snapshot(live: _Live) -> dict:
    return {"activity_id": live.activity_id, "kind": live.kind,
            "seq": live.seq, "payload": dict(live.payload)}
