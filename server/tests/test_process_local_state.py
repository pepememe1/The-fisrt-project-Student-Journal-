def test_the_scanner_actually_notices_new_state(tmp_path):
    """🔒 ОБРАТНЫЙ ХОД: сторож обязан УВИДЕТЬ вновь заведённое состояние.

    Без этого он неотличим от разбора, который молча ничего не находит, — а именно так
    выглядел `validate-agents.py`, три недели отвечавший «всё в порядке».
    """
    pkg = tmp_path / "app_like"
    pkg.mkdir()
    (pkg / "fresh.py").write_text(
        "import collections\n"
        "LIMIT = 5\n"                     # константа — не состояние
        "_sessions = {}\n"                # словарь литералом
        "_queue = collections.deque()\n"  # контейнер вызовом
        "def f():\n"
        "    local = {}\n"                # локальная переменная — не уровень модуля
        "    return local\n",
        encoding="utf-8")
    found = _scan(str(pkg))
    assert ("fresh.py", "_sessions") in found
    assert ("fresh.py", "_queue") in found
    assert ("fresh.py", "LIMIT") not in found, "константа не должна попадать в реестр"
    assert ("fresh.py", "local") not in found, "локальная переменная — не состояние модуля"
